 assert.equal((await redeemed).status(),200)
 await expect(customerPage.locator('#personal-redemption-code')).toHaveValue('')
 const after=await (await customer.request.get('/api/v1/billing/balance')).json()
 assert.equal(Number(after.settled_usd)-Number(before.settled_usd),50)
 await customerPage.screenshot({path:out+'/customer-redemption-mobile.png',fullPage:true});await customer.close()
