 await page.screenshot({path:out+'/proxy-mobile-dialog.png',fullPage:true})
 check('Phone pages have no document overflow; proxy dialog fits viewport')
 assert.deepEqual(errors,[])
 fs.writeFileSync(out+'/ui-checks.json',JSON.stringify({checks,errors},null,2))
