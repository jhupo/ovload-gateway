const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { chromium, expect } = createRequire('/src/web/package.json')('@playwright/test')
const live = process.argv.includes('live'), baseURL = 'https://192.168.2.150:19443'
const out = '/src/test-results/monitoring-completion'

async function main() {
  const browser = await chromium.launch({ args: ['--no-sandbox', '--disable-dev-shm-usage'] })
  const context = await browser.newContext({ baseURL, ignoreHTTPSErrors: true, locale: 'zh-CN', viewport: { width: 1920, height: 1080 } })
  await context.addInitScript(() => { localStorage.setItem('i18nextLng', 'zh'); document.cookie = 'vite-ui-theme=dark; path=/' })
  const response = await context.request.post('/api/v1/auth/sessions', { headers: { Origin: baseURL }, data: { login: 'ovload_test_admin', password: fs.readFileSync('/verify/administrator.password', 'utf8').trim() } })
  assert.equal(response.status(), 200)
  const auth = await response.json()
  if (!live) await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.pathname.startsWith('/api/') || url.pathname === '/healthz') return route.continue()
    const file = path.join('/src/web/dist-monitoring', url.pathname === '/monitoring' || url.pathname === '/' ? 'index.html' : url.pathname)
    if (fs.existsSync(file) && fs.statSync(file).isFile()) return route.fulfill({ path: file })
    return route.continue()
  })
  const page = await context.newPage(), errors = [], failed = [], checks = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('response', r => { if (r.url().includes('/api/') && r.status() >= 500) failed.push([r.status(),r.url()]) })
  try {
    await page.goto('/monitoring')
    const logs = page.getByTestId('system-logs'), resources = page.getByTestId('system-status')
    await expect(logs.getByRole('button',{name:'日志详情'}).first()).toBeVisible({ timeout: 30000 })
    await expect(resources).not.toContainText('未知')
    assert.equal(await page.getByText('运行错误历史',{exact:true}).count(),0)
    assert.equal(await page.getByText('告警事件',{exact:true}).count(),0)
    await logs.getByRole('button',{name:'日志详情'}).first().click()
    await expect(page.getByRole('dialog')).toContainText('日志级别')
    await page.keyboard.press('Escape')
    const request = page.waitForResponse(r => r.url().includes('/monitoring/logs?') && new URL(r.url()).searchParams.get('search') === 'missing-log-check-9439')
    await logs.getByRole('textbox',{name:'搜索日志'}).fill('missing-log-check-9439')
    assert.equal((await (await request).json()).total,0)
    await logs.getByRole('button',{name:'重置',exact:true}).click()
    await expect(logs.getByRole('button',{name:'日志详情'}).first()).toBeVisible()
    await logs.getByRole('button',{name:'高级筛选',exact:true}).click()
    await expect(page.getByRole('dialog').getByRole('textbox')).toHaveCount(2)
    await page.getByRole('dialog').getByRole('button',{name:'应用'}).click()
    await logs.getByRole('button',{name:'日志配置',exact:true}).click()
    const dialog=page.getByRole('dialog'), days=dialog.getByLabel('保留天数')
    await expect(days).toBeVisible()
    const old=await days.inputValue()
    await days.fill(old === '8' ? '9' : '8')
    const saved=page.waitForResponse(r => r.url().endsWith('/monitoring/logs/config') && r.request().method()==='PUT')
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    assert.equal((await saved).status(),200)
    await expect(dialog).not.toBeVisible()
    await logs.getByRole('button',{name:'日志配置',exact:true}).click()
    await expect(days).toHaveValue(old === '8' ? '9' : '8')
    await days.fill(old)
    await dialog.getByRole('button',{name:'保存',exact:true}).click()
    await expect(dialog).not.toBeVisible()
    await logs.getByRole('button',{name:'清理日志',exact:true}).click()
    await expect(dialog).toContainText('删除后无法恢复')
    await dialog.getByRole('button',{name:'取消'}).click()
    await page.getByTestId('monitoring-filters').getByRole('combobox').first().click()
    await expect(page.getByRole('option',{name:'Claude',exact:true})).toBeVisible()
    await expect(page.getByRole('option',{name:'Gemini',exact:true})).toBeVisible()
    await page.keyboard.press('Escape')
    await page.screenshot({path:`${out}/${live ? 'live' : 'candidate'}-desktop.png`,fullPage:true})
    await page.setViewportSize({width:390,height:844})
    await logs.scrollIntoViewIfNeeded()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await expect(logs.getByRole('table')).not.toBeVisible()
    await expect(logs.locator('article').first()).toBeVisible()
    await page.screenshot({path:`${out}/${live ? 'live' : 'candidate'}-mobile.png`,fullPage:true})
    assert.deepEqual(errors,[]); assert.deepEqual(failed,[])
    checks.push('Live resource cards, structured log details, filters, settings persistence, cleanup confirmation, provider choices and responsive layout')
    fs.writeFileSync(`${out}/${live ? 'live' : 'candidate'}.json`,JSON.stringify({passed:true,checks},null,2))
    console.log('PASS '+checks.join('; '))
  } finally {
    await context.request.delete('/api/admin/v1/auth/session',{headers:{Origin:baseURL,'X-CSRF-Token':auth.csrf_token}}).catch(()=>{})
    await browser.close()
  }
}
main().catch(e=>{console.error(e);process.exitCode=1})
