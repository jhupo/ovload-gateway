const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { chromium, expect } = createRequire('/src/web/package.json')('@playwright/test')
const live = process.argv.includes('live'), baseURL = 'https://192.168.2.150:19443'
const out = '/src/test-results/usage-contract'
async function main() {
  const browser = await chromium.launch({ args: ['--no-sandbox', '--disable-dev-shm-usage'] })
  const context = await browser.newContext({ baseURL, ignoreHTTPSErrors: true, locale: 'zh-CN', viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
  await context.addInitScript(() => localStorage.setItem('i18nextLng', 'zh'))
  const auth = await context.request.post('/api/v1/auth/sessions', { headers: { Origin: baseURL }, data: { login: 'ovload_test_admin', password: fs.readFileSync('/verify/administrator.password', 'utf8').trim() } })
  assert.equal(auth.status(), 200)
  if (!live) await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin !== baseURL || url.pathname.startsWith('/api/')) return route.continue()
    const file = path.join('/src/web/dist-usage-contract', route.request().resourceType() === 'document' ? 'index.html' : url.pathname)
    return fs.existsSync(file) && fs.statSync(file).isFile() ? route.fulfill({ path: file }) : route.continue()
  })
  const page = await context.newPage(), errors = [], failed = [], checks = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('response', r => { if (r.url().includes('/api/') && r.status() >= 400) failed.push(r.url()) })
  try {
    await page.goto('/usage'); await page.waitForLoadState('networkidle')
    await expect(page.getByPlaceholder('用户邮箱')).toBeVisible()
    await expect(page.getByText('时间范围 / 厂商汇总', { exact: true })).toHaveCount(0)
    await expect(page.getByPlaceholder('搜索 API 密钥名称')).toHaveCount(0)
    const recordsResponse = page.waitForResponse(r => r.url().includes('/usage/records?') && r.url().includes('userEmail=usage-demo-20261108'))
    await page.getByPlaceholder('用户邮箱').fill('usage-demo-20261108')
    const records = (await (await recordsResponse).json()).data.items
    assert.ok(records.length)
    const record = records.find(r => r.userName && r.logicalOutcome === 'succeeded') ?? records.find(r => r.userName)
    const detailResponse = page.waitForResponse(r => r.url().includes('/usage/records/detail?'))
    await page.locator(`[data-request-id="${record.id}"]`).first().click()
    const detail = (await (await detailResponse).json()).data
    const sheet = page.getByRole('dialog')
    await expect(sheet.getByText(detail.userName, { exact: true })).toBeVisible()
    await expect(sheet.getByText('暂不可用', { exact: true })).toHaveCount(0)
    await sheet.getByRole('tab', { name: '请求', exact: true }).click()
    await expect(sheet.getByText(detail.requestId, { exact: true }).last()).toBeVisible()
    await sheet.getByRole('tab', { name: '响应', exact: true }).click()
    await expect(sheet.getByText('响应 ID', { exact: true })).toBeVisible()
    await sheet.getByRole('tab', { name: '费用', exact: true }).click()
    await expect(sheet.getByText('图片输入', { exact: true })).toBeVisible()
    await expect(sheet.getByText('图片输出', { exact: true })).toBeVisible()
    await page.screenshot({ path: `${out}/${live ? 'live' : 'candidate'}-detail-desktop.png` })
    await page.setViewportSize({ width: 390, height: 844 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: `${out}/${live ? 'live' : 'candidate'}-detail-mobile.png` })
    await page.keyboard.press('Escape'); await page.setViewportSize({ width: 1440, height: 1000 })
    const download = page.waitForEvent('download'); await page.getByRole('button', { name: '导出', exact: true }).click()
    const csv = await download; await csv.saveAs(`${out}/usage.csv`)
    const text = fs.readFileSync(`${out}/usage.csv`, 'utf8')
    assert.match(text, /图片输入/); assert.match(text, /缓存写入/); assert.match(text, new RegExp(record.id))
    await page.getByRole('tab', { name: '非成功', exact: true }).click(); await page.waitForLoadState('networkidle')
    await expect(page.locator('table:visible')).toBeVisible()
    await page.screenshot({ path: `${out}/${live ? 'live' : 'candidate'}-errors.png` })
    await page.getByRole('combobox', { name: '时间', exact: true }).click()
    await page.getByRole('option', { name: '自定义', exact: true }).click()
    await page.getByRole('tab', { name: '用户排行', exact: true }).click()
    await page.waitForLoadState('networkidle')
    const rankingRefresh = page.waitForResponse(r => r.url().includes('/usage/ranking?') && r.url().includes('startTime='))
    await page.getByRole('button', { name: '刷新', exact: true }).click()
    assert.equal((await rankingRefresh).status(), 200)
    checks.push('Custom-date ranking refresh sends a new request using the backend time parameters')
    checks.push('Current entry, user/email filters, real detail fields, desktop/mobile layout, non-success tab and full CSV work against the deployed backend')
    if (!live) {
      const retry = await context.newPage()
      await retry.route('**/api/admin/usage/records?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 503, message: 'Service unavailable' }) }))
      await retry.goto('/usage'); await expect(retry.getByRole('button', { name: '重试', exact: true }).first()).toBeVisible()
      await retry.unroute('**/api/admin/usage/records?*')
      await retry.getByRole('button', { name: '重试', exact: true }).first().click()
      await expect(retry.locator('table:visible tbody tr').first()).toBeVisible()
      await retry.close(); checks.push('503 leaves a visible retry action and recovers to real records')
    }
    assert.deepEqual(errors, []); assert.deepEqual(failed, [])
    fs.writeFileSync(`${out}/${live ? 'live' : 'candidate'}.json`, JSON.stringify({ passed: true, checks }, null, 2))
    console.log(checks.map(c => 'PASS ' + c).join('\n'))
  } finally {
    const login = await auth.json()
    await context.request.delete('/api/admin/v1/auth/session', { headers: { Origin: baseURL, 'X-CSRF-Token': login.csrf_token } }).catch(() => {})
    await browser.close()
  }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
