const assert = require('node:assert/strict')
const fs = require('node:fs')
const { createRequire } = require('node:module')
const { chromium, expect } = createRequire('/src/web/package.json')('@playwright/test')
const zh = require('/src/web/src/i18n/locales/zh.json')
const base = 'https://192.168.2.150:19444'
const out = '/src/test-results/settings-completion'
const priv = JSON.parse(fs.readFileSync('/test-runtime/private.json', 'utf8'))
let browser
const checks = [], errors = []
const mark = (s) => { checks.push(s); console.log('PASS ' + s) }
async function json(response) {
  assert.equal(response.status(), 200, response.url() + ' ' + await response.text())
  return response.json()
}
async function context(login, password) {
  const ctx = await browser.newContext({ baseURL: base, ignoreHTTPSErrors: true, locale: 'zh-CN', viewport: { width: 1440, height: 1000 } })
  await ctx.addInitScript(() => { try { localStorage.setItem('i18nextLng', 'zh') } catch { /* Sandboxed mail previews have no storage. */ } })
  const session = await json(await ctx.request.post('/api/v1/auth/sessions', { headers: { Origin: base }, data: { login, password } }))
  ctx.on('page', (page) => page.on('pageerror', (e) => errors.push(e.message)))
  return { ctx, headers: { Origin: base, 'X-CSRF-Token': session.csrf_token } }
}
async function capture(page, name) {
  await page.screenshot({ path: `${out}/${name}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: `${out}/${name}-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
}
async function main() {
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disk-cache-size=33554432'] })
  const { ctx, headers } = await context('ovload_settings_verify', priv.administratorPassword)
  const page = await ctx.newPage()
  await page.goto('/mail-settings')
  await expect(page.locator('input[name="smtpHost"]')).toHaveValue('172.24.0.1')
  await expect(page.locator('input[name="smtpPassword"]')).toHaveValue('')
  const sender = 'Settings UI ' + Date.now()
  await page.locator('input[name="senderName"]').fill(sender)
  await page.getByRole('button', { name: zh.mailSettings.save, exact: true }).filter({ visible: true }).click()
  await expect.poll(async () => (await json(await ctx.request.get('/api/admin/v1/settings/integrations/mail'))).values.senderName).toBe(sender)
  await page.reload()
  await expect(page.locator('input[name="senderName"]')).toHaveValue(sender)
  await page.getByRole('button', { name: zh.mailSettings.testConnection, exact: true }).click()
  await capture(page, 'mail')
  await page.getByRole('tab', { name: zh.mailSettings.templates, exact: true }).click()
  await expect(page.locator('textarea').first()).toBeEnabled()
  await capture(page, 'mail-templates')
  mark('Mail UI saves server settings, survives reload, keeps passwords empty and exposes editable templates on desktop/mobile')

  await page.goto('/payment-settings')
  await expect(page.locator('input[name="subscriptionRate"]')).toHaveValue('7.15')
  await expect(page.locator('main')).not.toContainText('paymentSettings.')
  await capture(page, 'payment')
  await page.getByRole('tab', { name: zh.paymentSettings.alipay, exact: true }).click()
  await expect(page.locator('input[name="alipaySellerId"]')).toHaveValue('2088000000000001')
  await expect(page.locator('#payment-privateKey')).toHaveValue('')
  await expect(page.locator('#payment-publicKey')).toHaveValue('')
  await capture(page, 'payment-alipay')
  mark('Payment UI reads persisted rates and seller settings, renders Chinese labels and never exposes private keys')

  await page.goto('/feature-settings')
  const row = page.getByRole('row').filter({ hasText: 'Fixture audit' })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: zh.integrationSettings.testConnection, exact: true }).click()
  await expect(row).toContainText(/\d+ ms/)
  await row.getByRole('button', { name: zh.auditSettings.editNode + ' Fixture audit', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('input[type="password"]')).toBeEnabled()
  await expect(dialog.locator('input[type="password"]')).toHaveValue('')
  await capture(page, 'audit-node')
  await dialog.getByRole('button', { name: zh.common.cancel, exact: true }).click()
  mark('Audit UI tests saved credentials and permits node key/proxy editing')

  await page.goto('/data-backup')
  const toggle = page.getByRole('switch', { name: zh.dataBackup.enableStorage, exact: true })
  await expect(toggle).not.toBeChecked()
  await toggle.click(); await expect(toggle).toBeChecked()
  await page.reload(); await expect(toggle).toBeChecked()
  await toggle.click(); await expect(toggle).not.toBeChecked()
  await capture(page, 'backup')
  await page.getByRole('tab', { name: zh.dataBackup.scheduleTab, exact: true }).click()
  await expect(page.getByRole('button', { name: zh.dataBackup.createBackup, exact: true })).toBeDisabled()
  await expect(page.getByRole('switch', { name: zh.dataBackup.enableSchedule, exact: true })).toBeDisabled()
  mark('Backup UI persists storage state and disables create/schedule actions while storage is off')

  for (const route of ['/general-settings', '/page-settings', '/security-authentication']) {
    await page.goto(route)
    await expect(page.locator('main h1')).toBeVisible()
    await capture(page, route.slice(1))
  }
  if (priv.customerEmail) {
    const { ctx: user } = await context(priv.customerEmail, priv.customerNewPassword)
    await user.addCookies([{ name: 'vite-ui-theme', value: 'dark', url: base }])
    const payment = await user.newPage()
    await payment.goto('/user/recharge')
    const input = payment.locator('#recharge-amount')
    await expect(input).toBeEnabled(); await input.fill('11')
    const submit = payment.getByRole('button', { name: zh.userRecharge.confirmPayment, exact: true })
    await expect(submit).toBeEnabled(); await submit.click()
    const payDialog = payment.getByRole('dialog')
    await capture(payment, 'recharge-qr')
    await expect(payDialog.locator('svg[height="192"]')).toBeVisible()
    const first = await payDialog.locator('[data-slot="dialog-description"]').textContent()
    await payDialog.getByRole('button', { name: zh.integrationSettings.cancelOrder, exact: true }).click()
    await expect(payDialog).toContainText(zh.integrationSettings.status.cancelled)
    await payment.keyboard.press('Escape')
    await submit.click(); await expect(payDialog).toBeVisible()
    const second = await payDialog.locator('[data-slot="dialog-description"]').textContent()
    assert.notEqual(first, second)
    await payment.keyboard.press('Escape')
    await payment.goto('/user/orders')
    await expect(payment.getByRole('row').filter({ hasText: second.trim() })).toBeVisible()
    await capture(payment, 'customer-orders')
    mark('Customer creates an Alipay QR order, cancels it, creates a fresh same-amount order and sees real order history')
    await user.close()
  }
  const signInContext = await browser.newContext({ baseURL: base, ignoreHTTPSErrors: true, locale: 'zh-CN', viewport: { width: 1440, height: 1000 } })
  await signInContext.addInitScript(() => { try { localStorage.setItem('i18nextLng', 'zh') } catch { /* Sandboxed documents have no storage. */ } })
  const signInPage = await signInContext.newPage()
  signInPage.on('pageerror', (e) => errors.push(e.message))
  await signInPage.goto('/sign-in')
  await signInPage.locator('input[name="login"]').fill('ovload_settings_verify')
  await signInPage.locator('input[name="password"]').fill(priv.administratorPassword)
  await signInPage.locator('button[type="submit"]').click()
  await expect(signInPage).not.toHaveURL(/sign-in/)
  await signInPage.reload()
  await expect(signInPage.locator('main')).toBeVisible()
  await expect(signInPage).not.toHaveURL(/sign-in/)
  await signInContext.close()
  mark('Unified browser sign-in identifies administrators and restores the session after reload')
  assert.deepEqual(errors, [])
  fs.writeFileSync(out + '/ui-result.json', JSON.stringify({ checks, errors, mobileOverflow: false }, null, 2))
  await ctx.close()
}
main().catch((e) => { console.error(e); process.exitCode = 1 }).finally(async () => { if (browser) await browser.close() })
