test('preview uses sample variables and isolates active HTML and external resources', async ({ page }) => {
  const external: string[] = []
  page.on('request', request => {
    if (request.url().includes('example.invalid')) external.push(request.url())
  })
  await page.getByRole('tab', { name: 'Email templates', exact: true }).click()
  await page.getByLabel('HTML body', { exact: true }).fill('<p>Sample {{verification_code}}</p><script>parent.previewInjected=true</script><img src="https://example.invalid/tracker" onerror="parent.previewInjected=true"><a href="https://example.invalid/link">External</a><iframe src="https://example.invalid/frame"></iframe>')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  const frame = page.frameLocator('iframe[title="Email preview"]')
  await expect(frame.getByText('Sample 123456', { exact: true })).toBeVisible()
  await expect(page.locator('iframe[title="Email preview"]')).toHaveAttribute('sandbox', '')
  await expect(frame.locator('script, iframe, [onerror], a[href]')).toHaveCount(0)
  expect(await page.evaluate(() => 'previewInjected' in window)).toBe(false)
  expect(external).toHaveLength(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Preview', exact: true })).toBeFocused()
})

test('localized default emails render code and reset actions without overflow on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('tab', { name: 'Email templates', exact: true }).click()
  const frame = page.frameLocator('iframe[title="Email preview"]')
  for (const [language, title, resetTitle, greeting] of [
    ['English', 'Email verification code', 'Password reset', 'Hello Demo user,'],
    ['Simplified Chinese', '邮箱验证码', '密码重置', 'Demo user，您好：'],
  ]) {
    await page.getByLabel('Template language', { exact: true }).click()
    await page.getByRole('option', { name: language, exact: true }).click()
    await page.getByLabel('Template type', { exact: true }).click()
    await page.getByRole('option', { name: 'Email verification code', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(frame.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await expect(frame.getByText('123456', { exact: true })).toBeVisible()
    await expect(frame.getByText(greeting, { exact: true })).toBeVisible()
    await expect(frame.locator('body')).not.toContainText(/{{|}}/)
    expect(await frame.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await page.getByLabel('Template type', { exact: true }).click()
    await page.getByRole('option', { name: 'Password reset', exact: true }).click()
    await page.getByRole('button', { name: 'Preview', exact: true }).click()
    await expect(frame.getByRole('heading', { name: resetTitle, exact: true })).toBeVisible()
    await expect(frame.locator('a')).toHaveText(language === 'English' ? 'Reset password' : '重置密码')
    await expect(frame.locator('a')).not.toHaveAttribute('href')
    await expect(frame.getByText(/https:\/\/example.com\/reset-password/)).toBeVisible()
    expect(await frame.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Preview', exact: true })).toBeFocused()
  }
  // Saving validates every default event/language, including unselected templates.
  await page.getByLabel('Email subject', { exact: true }).fill('Default templates validation')
  await page.getByRole('button', { name: 'Save', exact: true }).filter({ visible: true }).click()
  await expect(page.getByRole('button', { name: 'Save', exact: true }).filter({ visible: true })).toBeDisabled()
  expect(await page.evaluate(() => sessionStorage.getItem('ovload.mail-settings.draft'))).not.toBeNull()
})

