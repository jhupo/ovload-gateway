  expect(stored.templates.passwordReset.en.subject).toBe('English reset {{site_name}}')
  expect(stored.templates.passwordReset.zh.subject).toBe('Chinese reset {{site_name}}')
  await page.reload()
  await page.getByRole('tab', { name: 'Email templates', exact: true }).click()
  await expect(subject).toHaveValue('English verification {{site_name}}')
