import { mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from '../../web/node_modules/@playwright/test'

const captures = join(tmpdir(), 'ovload-users-redesign-acceptance')
for (const mobile of [false, true]) {
  for (const theme of ['light', 'dark'] as const) {
    test(`users ${mobile ? 'mobile' : 'desktop'} ${theme}`, async ({ page }) => {
      const prefix = `${mobile ? 'mobile' : 'desktop'}-${theme}`
      await mkdir(captures, { recursive: true })
      await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.addInitScript(() => { localStorage.setItem('i18nextLng', 'zh'); sessionStorage.setItem('ovload.admin-preview', 'active') })
      const errors: string[] = []
      const writes: string[] = []
      page.on('pageerror', e => errors.push(e.message))
      page.on('request', r => { if (['POST', 'PATCH', 'PUT', 'DELETE'].includes(r.method())) writes.push(r.url()) })
      const capture = async (state: string) => { await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))) }); await page.screenshot({ path: join(captures, `${prefix}-${state}.png`) }) }
      await page.goto('/users')
      await expect(page.getByTestId('user-row')).toHaveCount(10)
      await expect(page.getByRole('columnheader')).toHaveCount(mobile ? 0 : 7)
      if (mobile) {
        const expand = page.getByRole('button', { name: '查看 lin.zhou 的时间', exact: true })
        await expand.click()
        await expect(expand).toHaveAttribute('aria-expanded', 'true')
        await expect(page.getByTestId('user-row').first()).toContainText('1001')
        await expect(page.getByRole('button', { name: 'lin.zhou 的余额', exact: true })).toBeInViewport()
        await expect(page.getByRole('button', { name: '操作 lin.zhou', exact: true })).toBeInViewport()
        await capture('expanded-time')
      }
      await expect(page.getByTestId('user-row').first()).toContainText('lin.zhou@example.com')
      await expect(page.getByTestId('user-row').first()).toContainText('最后调用')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await capture('table')
      await page.getByRole('button', { name: '邀请用户', exact: true }).click()
      const invite = page.getByRole('dialog')
      await expect(invite.getByRole('button', { name: '发送邀请', exact: true })).toBeDisabled()
      await capture('invite')
      await invite.getByLabel('邮箱', { exact: true }).fill('preview@example.com')
      await page.keyboard.press('Escape')
      await expect(invite).toBeVisible()
      await invite.getByRole('button', { name: '取消', exact: true }).click()
      await expect(page.getByRole('button', { name: '邀请用户', exact: true })).toBeFocused()
      await page.getByRole('button', { name: '新增用户', exact: true }).click()
      const create = page.getByRole('dialog')
      await expect(create.getByRole('button', { name: '新增用户', exact: true })).toBeDisabled()
      await capture('add')
      await create.getByLabel('密码', { exact: true }).fill('temporary-test-value')
      await create.getByLabel('确认密码', { exact: true }).fill('temporary-test-value')
      await page.keyboard.press('Escape')
      await expect(create).toBeVisible()
      await create.getByRole('button', { name: '取消', exact: true }).click()
      await expect(page.getByRole('button', { name: '新增用户', exact: true })).toBeFocused()
      await page.getByRole('button', { name: '新增用户', exact: true }).click()
      await expect(page.getByRole('dialog').getByLabel('密码', { exact: true })).toHaveValue('')
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: '状态', exact: true }).click()
      await page.getByRole('option', { name: /已禁用/ }).click()
      await page.keyboard.press('Escape')
      await expect(page.getByTestId('user-row')).toHaveCount(2)
      if (!mobile) await page.getByRole('columnheader', { name: '状态', exact: true }).scrollIntoViewIfNeeded()
      await capture('status-filter')
      await page.reload()
      await expect(page.getByTestId('user-row')).toHaveCount(2)
      await page.getByRole('button', { name: '重置', exact: true }).click()
      await expect(page.getByTestId('user-row')).toHaveCount(10)
      const action = page.getByRole('button', { name: '操作 lin.zhou', exact: true })
      await action.click()
      await capture('row-menu')
      await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
      const editor = page.getByRole('dialog')
      await expect(editor.getByLabel('并发数', { exact: true })).toHaveValue('5')
      await expect(editor.getByLabel('RPM', { exact: true })).toHaveValue('60')
      await expect(editor.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
      await capture('editor')
      await editor.getByRole('combobox', { name: '角色', exact: true }).click()
      await capture('editor-role-options')
      await page.keyboard.press('Escape')
      await editor.getByLabel('并发数', { exact: true }).fill('12')
      await editor.getByLabel('RPM', { exact: true }).fill('180')
      await editor.getByLabel('新密码', { exact: true }).fill('temporary-test-value')
      await editor.getByLabel('备注', { exact: true }).fill('Draft note')
      await page.keyboard.press('Escape')
      await expect(editor).toBeVisible()
      await editor.getByRole('button', { name: '取消', exact: true }).click()
      await expect(action).toBeFocused()
      await action.click()
      await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
      await expect(editor.getByLabel('新密码', { exact: true })).toHaveValue('')
      await expect(editor.getByLabel('并发数', { exact: true })).toHaveValue('5')
      await editor.getByRole('button', { name: '取消', exact: true }).click()
      await action.click()
      await page.getByRole('menuitem', { name: '禁用', exact: true }).click()
      await expect(page.getByRole('alertdialog').getByRole('button', { name: '禁用', exact: true })).toBeDisabled()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('alertdialog')).toBeVisible()
      await capture('status-dialog')
      await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click()
      await page.getByRole('button', { name: 'lin.zhou 的余额', exact: true }).click()
      const balance = page.getByRole('dialog')
      await expect(balance.locator('form')).toHaveCount(0)
      await expect(balance.getByRole('list').getByRole('listitem')).toHaveCount(3)
      await balance.getByRole('button', { name: '充值', exact: true }).click()
      const recharge = page.getByRole('dialog', { name: '充值', exact: true })
      await expect(recharge.getByRole('button', { name: '充值', exact: true })).toBeDisabled()
      await expect(recharge.getByLabel('金额 ($)', { exact: true })).toBeVisible()
      await capture('recharge')
      await recharge.getByLabel('金额 ($)', { exact: true }).fill('100.00')
      await recharge.getByLabel('备注', { exact: true }).fill('Draft recharge')
      await page.keyboard.press('Escape')
      await expect(recharge).toBeVisible()
      await recharge.getByRole('button', { name: '取消', exact: true }).click()
      await expect(balance.getByRole('button', { name: '充值', exact: true })).toBeFocused()
      await balance.getByRole('button', { name: '充值', exact: true }).click()
      await expect(recharge.getByLabel('金额 ($)', { exact: true })).toHaveValue('')
      await page.keyboard.press('Escape')
      await expect(balance).toBeVisible()
      await capture('history')
      await balance.getByRole('combobox', { name: '充值类型' }).click()
      await capture('history-filter-options')
      await page.getByRole('option', { name: '管理员充值', exact: true }).click()
      await expect(balance.getByRole('list').getByRole('listitem')).toHaveCount(1)
      await capture('filtered-history')
      await balance.getByRole('button', { name: '关闭', exact: true }).click()
      await action.click()
      await page.getByRole('menuitem', { name: '充值记录', exact: true }).click()
      await expect(page.getByRole('dialog').locator('form')).toHaveCount(0)
      await expect(page.getByRole('dialog').getByRole('list').getByRole('listitem')).toHaveCount(3)
      await page.keyboard.press('Escape')
      await expect(action).toBeFocused()
      await page.getByRole('textbox', { name: '搜索 ID、用户名或邮箱' }).fill('1006')
      await expect(page.getByTestId('user-row')).toHaveCount(1)
      await page.getByRole('button', { name: 'ava.liu 的余额', exact: true }).click()
      await expect(page.getByText('暂无充值记录', { exact: true })).toBeVisible()
      await capture('empty-history')
      await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()
      await page.getByRole('textbox', { name: '搜索 ID、用户名或邮箱' }).fill('missing-user')
      await expect(page.getByTestId('user-row')).toHaveCount(0)
      await capture('empty-table')
      expect(writes).toEqual([])
      expect(errors).toEqual([])
      const stored = await page.evaluate(() => JSON.stringify([localStorage, sessionStorage]))
      expect(stored).not.toContain('temporary-test-value')
    })
  }
}

test('original table filters, sorting, pagination and column visibility', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.addInitScript(() => { localStorage.setItem('i18nextLng', 'en'); sessionStorage.setItem('ovload.admin-preview', 'active') })
  await page.goto('/users')
  const rows = page.getByTestId('user-row')
  await expect(rows).toHaveCount(10)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(rows.first()).toContainText('1011')
  await expect(page).toHaveURL(/page=2/)
  await page.getByRole('combobox', { name: 'Rows per page' }).click()
  await page.getByRole('option', { name: '30', exact: true }).click()
  await expect(rows).toHaveCount(24)
  await page.reload()
  await expect(rows).toHaveCount(24)
  await page.getByRole('button', { name: 'ID', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Desc', exact: true }).click()
  await expect(rows.first()).toContainText('1024')
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Balance', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(page.getByRole('columnheader')).toHaveCount(6)
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Balance', exact: true }).click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.getByRole('button', { name: 'Role', exact: true }).click()
  await page.getByRole('option', { name: /Admin/ }).click()
  await page.keyboard.press('Escape')
  await expect(rows).toHaveCount(3)
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search ID, username or email' }).fill('nina.li@example.com')
  await expect(rows).toHaveCount(1)
  await page.getByRole('button', { name: 'Actions for nina.li' }).click()
  await expect(page.getByRole('menuitem', { name: 'Enable', exact: true })).toBeVisible()
})
