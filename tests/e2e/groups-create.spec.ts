import { mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from '../../web/node_modules/@playwright/test'

const captures = join(tmpdir(), 'ovload-groups-create-20260930')
for (const mobile of [false, true]) {
  for (const theme of ['light', 'dark'] as const) {
    test(`create group ${mobile ? 'mobile' : 'desktop'} ${theme}`, async ({ page }) => {
      await mkdir(captures, { recursive: true })
      await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.addInitScript(() => {
        localStorage.setItem('i18nextLng', 'zh')
        sessionStorage.setItem('ovload.admin-preview', 'active')
      })
      const errors: string[] = []
      const writes: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('request', request => {
        if (['POST', 'PATCH', 'PUT', 'DELETE'].includes(request.method())) writes.push(request.url())
      })
      const capture = async (state: string) => {
        await page.evaluate(async () => {
          await Promise.all(document.getAnimations().filter(a => a.effect?.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {})))
        })
        await page.screenshot({ path: join(captures, `${mobile ? 'mobile' : 'desktop'}-${theme}-${state}.png`) })
      }
      await page.goto('/groups')
      await expect(page.getByTestId('group-row')).toHaveCount(10)
      const trigger = page.getByRole('button', { name: '创建分组', exact: true })
      await trigger.focus()
      await capture('header')
      await trigger.press('Enter')
      const dialog = page.getByRole('dialog')
      const body = page.getByTestId('group-editor-body')
      await expect(dialog.getByLabel('名称', { exact: true })).toHaveValue('')
      await expect(dialog.getByLabel('每分钟 RPM', { exact: true })).toHaveValue('')
      await expect(dialog.getByRole('button', { name: '创建分组', exact: true })).toBeDisabled()
      await expect(dialog.getByRole('tab')).toHaveCount(0)
      await capture('blank')
      await page.keyboard.press('Escape')
      await expect(trigger).toBeFocused()
      await trigger.click()
      await dialog.getByLabel('名称', { exact: true }).fill('Preview creation draft')
      await dialog.getByRole('combobox', { name: '平台', exact: true }).click()
      await expect(page.getByRole('option')).toHaveCount(5)
      await capture('platforms')
      await page.getByRole('option', { name: 'Antigravity', exact: true }).click()
      await dialog.getByLabel('每分钟 RPM', { exact: true }).fill('300')
      await body.evaluate(el => { el.scrollTop = 0 })
      await capture('filled')
      await page.keyboard.press('Escape')
      await expect(dialog).toBeVisible()
      await page.mouse.click(5, 5)
      await expect(dialog).toBeVisible()
      await body.hover()
      await page.mouse.wheel(0, 400)
      await expect.poll(() => body.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
      await dialog.getByRole('switch', { name: '图片单独计费', exact: true }).click()
      await dialog.getByLabel('1K 单价 (OVL / 张)', { exact: true }).fill('0.05')
      await dialog.getByRole('heading', { name: '计费', exact: true }).evaluate(el => el.scrollIntoView({ block: 'start' }))
      await capture('billing')
      await dialog.getByRole('heading', { name: '模型计价', exact: true }).evaluate(el => el.scrollIntoView({ block: 'start' }))
      await expect(dialog.getByTestId('model-price')).toHaveCount(0)
      await expect(dialog.getByTestId('model-mapping')).toHaveCount(0)
      await capture('rules-empty')
      await dialog.getByRole('button', { name: '添加映射', exact: true }).click()
      await dialog.getByLabel('请求模型', { exact: true }).fill('client-model')
      await dialog.getByLabel('目标模型', { exact: true }).fill('target-model')
      await expect(dialog.getByRole('heading', { name: /^创建分组/ })).toBeInViewport({ ratio: 1 })
      await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeInViewport({ ratio: 1 })
      expect(await dialog.evaluate(el => el.scrollTop)).toBe(0)
      await capture('mapping')
      await dialog.getByRole('button', { name: '取消', exact: true }).click()
      await expect(trigger).toBeFocused()
      await trigger.click()
      await expect(dialog.getByLabel('名称', { exact: true })).toHaveValue('')
      await expect(dialog.getByRole('combobox', { name: '平台', exact: true })).toHaveText('选择平台')
      await expect(dialog.getByTestId('model-mapping')).toHaveCount(0)
      await expect(dialog.getByRole('switch', { name: '图片单独计费', exact: true })).not.toBeChecked()
      await page.keyboard.press('Escape')
      await expect(page.getByTestId('group-row')).toHaveCount(10)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect(await page.evaluate(() => JSON.stringify([localStorage, sessionStorage]))).not.toContain('Preview creation draft')
      expect(writes).toEqual([])
      expect(errors).toEqual([])
    })
  }
}

test('create group English labels and keyboard platform selection', async ({ page }) => {
  await page.addInitScript(() => { localStorage.setItem('i18nextLng', 'en'); sessionStorage.setItem('ovload.admin-preview', 'active') })
  await page.goto('/groups')
  const trigger = page.getByRole('button', { name: 'Create group', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Platform', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await expect(dialog.getByRole('combobox', { name: 'Platform', exact: true })).toHaveText('OpenAI API')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(trigger).toBeFocused()
})
