test('password controls use native autocomplete, toggle visibility and never persist or submit', async ({ page }) => {
  const mutations: string[] = []
  page.on('request', request => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) mutations.push(request.url()) })
  const form = page.getByRole('form', { name: 'Profile', exact: true })
  const value = await page.evaluate(() => crypto.randomUUID())
  for (const [label, autocomplete] of [['Current password', 'current-password'], ['New password', 'new-password'], ['Confirm new password', 'new-password']]) {
    const input = form.getByLabel(label, { exact: true })
    await expect(input).toHaveAttribute('type', 'password')
    await expect(input).toHaveAttribute('autocomplete', autocomplete)
    await input.fill(value)
  }
  await expect(page.getByText('Backend not connected', { exact: true })).toBeVisible()
  await expect(form.getByRole('button', { name: 'Change password', exact: true })).toHaveCount(0)
  await expect(save(page)).toBeEnabled()
  const current = form.getByLabel('Current password', { exact: true })
  await current.locator('..').getByRole('button', { name: 'Show password', exact: true }).click()
  await expect(current).toHaveAttribute('type', 'text')
  await current.locator('..').getByRole('button', { name: 'Hide password', exact: true }).click()
  await save(page).click()
  await expect(page.locator('[data-sonner-toast]')).toContainText('Backend not connected')
  expect(await page.evaluate(() => JSON.stringify({ ...sessionStorage, ...localStorage }))).not.toContain(value)
  expect(mutations).toEqual([])
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(current).toHaveValue('')
  await expect(form.getByLabel('New password', { exact: true })).toHaveValue('')
  await expect(form.getByLabel('Confirm new password', { exact: true })).toHaveValue('')
  await expect(save(page)).toBeDisabled()
})

test('unified profile actions validate passwords and preserve the whole draft until discarded', async ({ page }) => {
  const username = page.getByRole('textbox', { name: 'Username', exact: true })
  const current = page.getByLabel('Current password', { exact: true })
  const next = page.getByLabel('New password', { exact: true })
  const confirm = page.getByLabel('Confirm new password', { exact: true })
  const value = await page.evaluate(() => crypto.randomUUID())
  await username.fill('Pending profile')
  await next.fill(value)
  await save(page).click()
  await expect(current).toBeFocused()
  await expect(current).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('[data-sonner-toast]')).toContainText('Enter the current password, new password and password confirmation')
  await current.fill(value)
  await confirm.fill(value + '-different')
  await save(page).click()
  await expect(confirm).toBeFocused()
  await expect(confirm).toHaveAttribute('aria-invalid', 'true')
  await confirm.fill(value)
  await save(page).click()
  await expect(summary(page).getByRole('heading')).toHaveText('ovload')
  await expect(username).toHaveValue('Pending profile')
  await page.getByRole('link', { name: 'Channel status', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(next).toHaveValue(value)
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(username).toHaveValue('ovload')
  await expect(next).toHaveValue('')
  await expect(confirm).toHaveValue('')
  await username.fill('Profile only')
  await save(page).click()
  await expect(summary(page).getByRole('heading')).toHaveText('Profile only')
})
