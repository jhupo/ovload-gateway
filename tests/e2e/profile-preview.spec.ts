test('username validation focuses errors, then summary and dropdown update without API writes', async ({ page }) => {
  const mutations: string[] = []
  page.on('request', request => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) mutations.push(request.url()) })
  const username = page.getByRole('textbox', { name: 'Username', exact: true })
  await username.fill('x')
  await save(page).click()
  await expect(username).toBeFocused()
  await expect(username).toHaveAttribute('aria-invalid', 'true')
  await expect(summary(page).getByRole('heading')).toHaveText('ovload')
  await username.fill('a'.repeat(31))
  await save(page).click()
  await expect(username).toHaveAttribute('aria-invalid', 'true')
  await username.fill('  Preview user  ')
  await save(page).click()
  await expect(username).toHaveValue('Preview user')
  await expect(save(page)).toBeDisabled()
  await expect(summary(page).getByRole('heading')).toHaveText('Preview user')
  await page.getByRole('button', { name: 'Administrator', exact: true }).click()
  await expect(page.getByRole('menu')).toContainText('Preview user')
  await expect(page.getByRole('menu')).toContainText('admin@example.com')
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Channel status', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Channel status', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Administrator', exact: true }).click()
  await page.getByRole('menuitem', { name: /Profile/ }).click()
  await expect(username).toHaveValue('Preview user')
  expect(await page.evaluate(() => JSON.stringify({ ...sessionStorage, ...localStorage }))).not.toContain('Preview user')
  await page.reload()
  await expect(username).toHaveValue('ovload')
  expect(mutations).toEqual([])
})

test('avatar changes require saving and invalid files preserve the valid draft', async ({ page }) => {
  const file = page.getByLabel('Avatar', { exact: true })
  const picker = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Choose avatar', exact: true }).focus()
  await page.keyboard.press('Enter')
  await (await picker).setFiles(await png(page))
  const draftAvatar = page.locator('form [data-slot=avatar-image]')
  await expect(draftAvatar).toHaveAttribute('src', /^data:image\/png;base64,/)
  const source = await draftAvatar.getAttribute('src')
  await expect(page.getByRole('button', { name: 'Administrator', exact: true }).locator('img')).toHaveCount(0)
  await file.setInputFiles({ name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await expect(page.getByText('Choose a PNG, JPEG or WebP image', { exact: true })).toBeVisible()
  await expect(draftAvatar).toHaveAttribute('src', source!)
  await file.setInputFiles({ name: 'bad.png', mimeType: 'image/png', buffer: Buffer.from('corrupt') })
  await expect(page.getByText('Unable to read this image. Choose a valid PNG, JPEG or WebP file', { exact: true })).toBeVisible()
  await expect(draftAvatar).toHaveAttribute('src', source!)
  await save(page).click()
  await expect(summary(page).locator('img')).toHaveAttribute('src', source!)
  await expect(page.getByRole('button', { name: 'Administrator', exact: true }).locator('img')).toHaveAttribute('src', source!)
  await file.setInputFiles(await png(page, '#785ba8'))
  await expect(draftAvatar).not.toHaveAttribute('src', source!)
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(draftAvatar).toHaveAttribute('src', source!)
  await expect(save(page)).toBeDisabled()
})

