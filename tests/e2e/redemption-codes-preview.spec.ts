import { expect, test } from '../../web/node_modules/@playwright/test'

test('redemption preview validates limits, generates bounded batches and retains history', async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('ovload.admin-preview', 'active')
    localStorage.setItem('i18nextLng', 'en')
  })
  await page.goto('/redemption-codes')
  await page.getByRole('button', { name: 'Generate codes', exact: true }).click()
  await page.getByLabel('Uses per user', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Generate preview codes', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('Uses per user', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Total uses per code', { exact: true }).fill('10')
  await page.getByLabel('Quantity (1–100)', { exact: true }).fill('101')
  await page.getByRole('button', { name: 'Generate preview codes', exact: true }).click()
  await expect(page.getByLabel('Quantity (1–100)', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Quantity (1–100)', { exact: true }).fill('2')
  await page.getByLabel('Notes', { exact: true }).fill('Preview batch')
  await page.getByRole('button', { name: 'Generate preview codes', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByRole('textbox', { name: 'Search code, notes, user email' }).fill('Preview batch')
  await expect(page.getByText('Preview batch', { exact: true }).filter({visible:true})).toHaveCount(2)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  expect((await downloadPromise).suggestedFilename()).toBe('redemption-preview.csv')
  await page.reload()
  await page.getByRole('textbox', { name: 'Search code, notes, user email' }).fill('Preview batch')
  await expect(page.getByText('No matching codes', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search code, notes, user email' }).fill('DEMO-0001')
  await page.getByRole('button', { name: 'More actions DEMO-0001-OVLOAD', exact:true }).filter({visible:true}).click()
  await expect(page.getByRole('menuitem', {name:'Delete',exact:true})).toBeDisabled()
  await page.getByRole('menuitem', {name:'Redemption history',exact:true}).click()
  await expect(page.getByRole('dialog').getByText('alex@example.com')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Generate codes', exact: true }).click()
  await page.getByLabel('Notes', { exact: true }).fill('Unsaved')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('alertdialog')).toBeVisible()
})
