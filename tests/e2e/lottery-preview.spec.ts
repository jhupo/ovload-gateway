import { expect, test, type Page } from '../../web/node_modules/@playwright/test'

const key = 'ovload.lottery.draft'
const save = (page: Page) => page.getByRole('button', { name: 'Save', exact: true }).filter({ visible: true })
const lotteryTab = (page: Page) => page.getByRole('tab', { name: 'Lottery', exact: true }).click()
const openEditor = (page: Page) => page.getByRole('button', { name: 'Start lottery', exact: true }).click()

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => { sessionStorage.setItem('ovload.admin-preview', 'active'); localStorage.setItem('i18nextLng', 'en') })
  await page.goto('/page-settings')
  await lotteryTab(page)
})

test('visibility is independent, defaults off and gates direct visits after reload', async ({ page }) => {
  const toggle = page.getByRole('switch', { name: 'Lottery page', exact: true })
  await expect(toggle).not.toBeChecked()
  await expect(page.getByRole('link', { name: 'Lottery', exact: true })).toHaveCount(0)
  await page.goto('/lottery')
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.goto('/page-settings'); await lotteryTab(page)
  await toggle.click()
  await expect(page.getByRole('link', { name: 'Lottery', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Channel status', exact: true })).toBeVisible()
  await page.reload(); await lotteryTab(page)
  await expect(toggle).toBeChecked()
  await toggle.click(); await page.goto('/lottery')
  await expect(page).toHaveURL(/\/dashboard$/)
})

test('modal rules are independent of pending monitoring changes and retain validation', async ({ page }) => {
  await page.getByRole('tab', { name: 'Channel monitoring', exact: true }).click()
  await page.getByLabel('Minimum samples', { exact: true }).fill('51')
  await lotteryTab(page); await openEditor(page)
  await page.getByLabel('Participants to draw', { exact: true }).fill('19')
  await page.getByRole('dialog').getByRole('button', { name: 'Start preview', exact: true }).click()
  await expect(page.getByLabel('Participants to draw', { exact: true })).toBeFocused()
  await page.getByLabel('Participants to draw', { exact: true }).fill('80')
  await page.getByRole('dialog').getByRole('button', { name: 'Start preview', exact: true }).click()
  await expect(page.getByTestId('lottery-managed-round')).toContainText('Round #167')
  expect(await page.evaluate(() => sessionStorage.getItem('ovload.channel-monitoring.draft'))).toBeNull()
  await page.getByRole('tab', { name: 'Channel monitoring', exact: true }).click()
  await expect(page.getByLabel('Minimum samples', { exact: true })).toHaveValue('51')
  await expect(save(page)).toBeEnabled()
  await save(page).click()
  expect(await page.evaluate(key => JSON.parse(sessionStorage.getItem(key)!).participantTarget, key)).toBe('80')
  await page.getByLabel('Minimum samples', { exact: true }).fill('52')
  await page.getByRole('link', { name: 'Channel status', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page).toHaveURL(/\/page-settings$/)
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByLabel('Minimum samples', { exact: true })).toHaveValue('51')
})

test('malformed lottery defaults survive monitoring saves and failed visibility changes', async ({ page }) => {
  await page.evaluate(key => sessionStorage.setItem(key, '{'), key)
  await page.reload(); await lotteryTab(page); await openEditor(page)
  await expect(page.getByText('The stored lottery draft could not be loaded. Defaults are shown; stored data has been preserved.', { exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('tab', { name: 'Channel monitoring', exact: true }).click()
  await page.getByLabel('Minimum samples', { exact: true }).fill('51'); await save(page).click()
  expect(await page.evaluate(key => sessionStorage.getItem(key), key)).toBe('{')
  await lotteryTab(page)
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'ovload.lottery.preview') throw new DOMException('Storage blocked', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await page.getByRole('switch', { name: 'Lottery page', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Lottery page', exact: true })).not.toBeChecked()
  await expect(page.getByRole('link', { name: 'Lottery', exact: true })).toHaveCount(0)
  await expect(page.getByText('Unable to save the switch. Check browser storage permissions', { exact: true })).toBeVisible()
})

test('public round history supports search, numeric sorting and pagination', async ({ page }) => {
  await page.getByRole('switch', { name: 'Lottery page', exact: true }).check()
  await page.getByRole('link', { name: 'Lottery', exact: true }).click()
  const section = page.getByTestId('lottery-rounds')
  const table = section.getByRole('table', { name: 'Past rounds', exact: true })
  await expect(table.getByRole('row')).toHaveCount(11)
  await section.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(table.getByRole('cell', { name: '#156', exact: true })).toBeVisible()
  await section.getByRole('textbox', { name: 'Search round number', exact: true }).fill('166')
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(table.getByRole('cell', { name: '#166', exact: true })).toBeVisible()
  await section.getByRole('textbox', { name: 'Search round number', exact: true }).fill('999')
  await expect(table).toContainText('No matching rounds')
  await section.getByRole('button', { name: 'Reset', exact: true }).click()
  await table.getByRole('columnheader', { name: 'Round', exact: true }).getByRole('button').click()
  await page.getByRole('menuitem', { name: 'Asc', exact: true }).click()
  await expect(table.getByRole('row').nth(1)).toContainText('#151')
})

