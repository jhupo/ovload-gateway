import { expect, test, type Page } from '../../web/node_modules/@playwright/test'

const storageKey = 'ovload.gateway-settings.draft.v1'
const save = (page: Page) => page.getByRole('button', { name: 'Save', exact: true }).filter({ visible: true }).click()
const tab = (page: Page, name: string) => page.getByRole('tab', { name, exact: true }).click()

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('ovload.admin-preview', 'active')
    localStorage.setItem('i18nextLng', 'en')
  })
  await page.goto('/gateway-settings')
})

test('keeps four tabs and saves only retained settings without sending mutations', async ({ page }) => {
  const mutations: string[] = []
  page.on('request', (request) => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) mutations.push(request.url()) })
  await expect(page.getByRole('tab')).toHaveText(['Basic settings', 'Failure handling', 'Codex settings', 'Model pricing'])
  await expect(page.getByRole('switch', { name: 'Allow users to view their own failed requests', exact: true })).toHaveCount(0)
  const headerInsets = await page.locator('[data-slot="card-header"]').evaluateAll((headers) => headers.map((header) => {
    const style = getComputedStyle(header)
    return { top: style.paddingTop, bottom: style.paddingBottom }
  }))
  expect(headerInsets.length).toBeGreaterThan(0)
  for (const insets of headerInsets) expect(insets.top).toBe(insets.bottom)
  await expect(page.getByRole('tab', { name: 'Scheduling', exact: true })).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Upstream settings', exact: true })).toHaveCount(0)
  await page.getByLabel('Connection timeout (s)', { exact: true }).fill('20')
  await page.getByLabel('Default 429 cooldown (s)', { exact: true }).fill('90')
  await page.getByLabel('529 overload cooldown (s)', { exact: true }).fill('180')
  await page.getByLabel('Connection timeout (s)', { exact: true }).press('Enter')
  await expect(page.getByRole('button', { name: 'Save', exact: true }).filter({ visible: true })).toBeDisabled()
  await tab(page, 'Failure handling')
  await expect(page.getByLabel('Default 429 cooldown (s)', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('529 overload cooldown (s)', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Recovery probe', exact: true })).toHaveCount(0)
  await page.getByLabel('Failure count threshold', { exact: true }).fill('5')
  const protectionHeader = page.locator('[data-slot="card-header"]').filter({ has: page.getByRole('heading', { name: 'Repeated failure protection', exact: true }) })
  await protectionHeader.getByRole('switch', { name: 'Enable repeated failure protection', exact: true }).uncheck()
  const streamHeader = page.locator('[data-slot="card-header"]').filter({ has: page.getByRole('heading', { name: 'Stream timeout handling', exact: true }) })
  await streamHeader.getByRole('combobox', { name: 'Timeout action', exact: true }).click()
  await page.getByRole('option', { name: 'Mark account as errored', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Credential refresh', exact: true })).toHaveCount(0)
  await expect(page.getByRole('table')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Add (model alias|platform policy)/ })).toHaveCount(0)
  await save(page)
  const stored = await page.evaluate((key) => JSON.parse(sessionStorage.getItem(key)!), storageKey)
  expect(stored).toMatchObject({ connectTimeout: '20', failureThreshold: '5', rateLimitCooldown: '90', overloadCooldown: '180', protectionEnabled: false, streamAction: 'error' })
  expect(stored).not.toHaveProperty('viewErrors')
  for (const key of ['strategy', 'affinity', 'affinityHours', 'maxRotations', 'accountConcurrency', 'keyQueue', 'accountQueue', 'queueTimeout', 'quotaThreshold', 'recoveryProbe', 'probeModel', 'aliases', 'policies', 'refreshMargin', 'refreshConcurrency']) expect(stored).not.toHaveProperty(key)
  await page.reload()
  await expect(page.getByLabel('Connection timeout (s)', { exact: true })).toHaveValue('20')
  await expect(page.getByLabel('Default 429 cooldown (s)', { exact: true })).toHaveValue('90')
  await expect(page.getByLabel('529 overload cooldown (s)', { exact: true })).toHaveValue('180')
  await tab(page, 'Failure handling')
  await expect(page.getByRole('switch', { name: 'Enable repeated failure protection', exact: true })).not.toBeChecked()
  await expect(page.getByRole('combobox', { name: 'Timeout action', exact: true })).toHaveText('Mark account as errored')
  expect(mutations).toEqual([])
})

test('existing drafts preserve active values while dropping deleted settings on save', async ({ page }) => {
  await page.getByLabel('Retention days', { exact: true }).fill('45')
  await save(page)
  await page.evaluate((key) => {
    const draft = JSON.parse(sessionStorage.getItem(key)!)
    sessionStorage.setItem(key, JSON.stringify({ ...draft, viewErrors: true, accountConcurrency: '0', quotaThreshold: 'invalid', aliases: null, policies: null, recoveryProbe: true, refreshMargin: 'invalid', refreshConcurrency: null }))
  }, storageKey)
  await page.reload()
  await expect(page.getByLabel('Retention days', { exact: true })).toHaveValue('45')
  await page.getByLabel('Retention days', { exact: true }).fill('46')
  await save(page)
  const stored = await page.evaluate((key) => JSON.parse(sessionStorage.getItem(key)!), storageKey)
  expect(stored.retentionDays).toBe('46')
  expect(stored).not.toHaveProperty('aliases')
  expect(stored).not.toHaveProperty('accountConcurrency')
  expect(stored).not.toHaveProperty('refreshMargin')
  expect(stored).not.toHaveProperty('refreshConcurrency')
  expect(stored).not.toHaveProperty('viewErrors')
})

test('validates hidden tabs and preserves discard and storage-error feedback', async ({ page }) => {
  await page.getByLabel('529 overload cooldown (s)', { exact: true }).fill('0')
  await tab(page, 'Failure handling')
  await save(page)
  await expect(page.getByLabel('529 overload cooldown (s)', { exact: true })).toBeFocused()
  await page.getByLabel('529 overload cooldown (s)', { exact: true }).fill('120')
  await tab(page, 'Failure handling')
  await page.getByLabel('Failure count threshold', { exact: true }).fill('0')
  await tab(page, 'Basic settings')
  await save(page)
  await expect(page.getByLabel('Failure count threshold', { exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByLabel('Failure count threshold', { exact: true })).toHaveValue('0')
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard', exact: true }).click()
  await expect(page.getByLabel('Failure count threshold', { exact: true })).toHaveValue('3')
  await page.getByLabel('Failure count threshold', { exact: true }).fill('4')
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'ovload.gateway-settings.draft.v1') throw new DOMException('Denied', 'QuotaExceededError')
      original.call(this, key, value)
    }
  })
  await save(page)
  await expect(page.getByText('Unable to save the draft. Check browser storage permissions', { exact: true })).toBeVisible()
  expect(await page.evaluate((key) => sessionStorage.getItem(key), storageKey)).toBeNull()
})

