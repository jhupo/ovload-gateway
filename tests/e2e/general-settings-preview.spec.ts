import { expect, test, type Page } from '../../web/node_modules/@playwright/test'

const save = (page: Page) =>
  page.getByRole('button', { name: 'Save', exact: true }).filter({ visible: true })

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('ovload.admin-preview', 'active')
    localStorage.setItem('i18nextLng', 'en')
  })
  await page.goto('/general-settings')
})

test('registration defaults validate across tabs and preserve save/discard behavior', async ({ page }) => {
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  await page.getByRole('switch', { name: 'Open registration', exact: true }).click()
  await page.getByLabel('Default concurrency', { exact: true }).fill('0')
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await save(page).click()
  await expect(page.getByRole('tab', { name: 'Register & login', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByLabel('Default concurrency', { exact: true })).toBeFocused()
  await expect(page.getByLabel('Default concurrency', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  expect(await page.evaluate(() => sessionStorage.getItem('ovload.general-settings.draft'))).toBeNull()
  await page.getByLabel('Default concurrency', { exact: true }).fill('8')
  await page.getByLabel('Default balance', { exact: true }).fill('12.50')
  await save(page).click()
  await expect(save(page)).toBeDisabled()
  await page.reload()
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Open registration', exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Default balance', { exact: true })).toHaveValue('12.50')
  await expect(page.getByLabel('Default concurrency', { exact: true })).toHaveValue('8')
  await page.getByLabel('Default concurrency', { exact: true }).fill('9')
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByLabel('Default concurrency', { exact: true })).toHaveValue('8')
})

test('email whitelist validates domains and preserves normalized save and discard behavior', async ({ page }) => {
  const loginTab = page.getByRole('tab', { name: 'Register & login', exact: true })
  await loginTab.click()
  const whitelist = page.getByLabel('Email whitelist', { exact: true })
  await expect(whitelist).toHaveValue('')
  for (const invalid of ['@', 'user@example.com', 'https://example.com', '*.example.com', '127.0.0.1', '-bad.example', 'a'.repeat(64) + '.com', Array.from({ length: 101 }, (_, index) => 'mail' + index + '.example').join(',')]) {
    await whitelist.fill(invalid)
    await page.getByRole('tab', { name: 'General', exact: true }).click()
    await save(page).click()
    await expect(loginTab).toHaveAttribute('aria-selected', 'true')
    await expect(whitelist).toBeFocused()
    await expect(whitelist).toHaveAttribute('aria-invalid', 'true')
    expect(await page.evaluate(() => sessionStorage.getItem('ovload.general-settings.draft'))).toBeNull()
  }
  await whitelist.fill(' @GMAIL.COM, outlook.com，gmail.com\nmail.example.com ')
  await save(page).click()
  await expect(save(page)).toBeDisabled()
  await expect(whitelist).toHaveValue('gmail.com\noutlook.com\nmail.example.com')
  await page.reload()
  await loginTab.click()
  await expect(whitelist).toHaveValue('gmail.com\noutlook.com\nmail.example.com')
  await whitelist.fill('unsaved.example')
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(whitelist).toHaveValue('gmail.com\noutlook.com\nmail.example.com')
  await whitelist.fill('')
  await save(page).click()
  const stored = await page.evaluate(() => JSON.parse(sessionStorage.getItem('ovload.general-settings.draft')!))
  expect(stored.login.emailWhitelist).toBe('')
})

test('password recovery policy saves, reloads, and discards independently of registration', async ({ page }) => {
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  const recovery = page.getByRole('switch', { name: 'Allow password recovery', exact: true })
  const registration = page.getByRole('switch', { name: 'Open registration', exact: true })
  const verification = page.getByRole('switch', { name: 'Email verification', exact: true })
  const registrationCard = page
    .locator('[data-slot="card"]')
    .filter({ has: registration })
    .filter({ has: page.locator('#registration-email-whitelist') })
  await expect(registrationCard.getByRole('switch')).toHaveCount(3)
  const cards = ['GitHub', 'Google', 'LinuxDo'].map((name) =>
    page.getByRole('heading', { name, exact: true }).locator('xpath=ancestor::div[@data-slot="card"][1]')
  )
  for (const card of cards) await expect(card).toHaveCount(1)
  const githubBox = await cards[0].boundingBox()
  const googleBox = await cards[1].boundingBox()
  const linuxdoBox = await cards[2].boundingBox()
  expect(googleBox?.x).toBeGreaterThan(githubBox?.x ?? 0)
  expect(linuxdoBox?.x).toBeGreaterThan(googleBox?.x ?? 0)
  await expect(recovery).not.toBeChecked()
  await recovery.check()
  await registration.uncheck()
  await verification.uncheck()
  await page.getByLabel('Password recovery frontend URL', { exact: true }).fill('https://dash.example.com/')
  await save(page).click()
  await expect(save(page)).toBeDisabled()
  await page.reload()
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  await expect(recovery).toBeChecked()
  await expect(registration).not.toBeChecked()
  await expect(verification).not.toBeChecked()
  await expect(page.getByLabel('Password recovery frontend URL', { exact: true })).toHaveValue('https://dash.example.com/')
  await recovery.uncheck()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(recovery).toBeChecked()
  const stored = await page.evaluate(() => JSON.parse(sessionStorage.getItem('ovload.general-settings.draft')!))
  expect(stored.login.passwordRecoveryEnabled).toBe(true)
  expect(stored.login.passwordRecoveryUrl).toBe('https://dash.example.com/')
})

test('website quick login contains only switches and saves without provider configuration', async ({ page }) => {
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  for (const provider of ['GitHub', 'Google', 'LinuxDo']) {
    await page.getByRole('switch', { name: provider + ' Quick login', exact: true }).check()
  }
  await expect(page.locator('#github-client-id')).toHaveCount(0)
  await expect(page.getByLabel('Pending identity lifetime', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('switch', { name: 'Allow identity binding', exact: true })).toHaveCount(0)
  await save(page).click()
  await expect(save(page)).toBeDisabled()
  const stored = await page.evaluate(() => JSON.parse(sessionStorage.getItem('ovload.general-settings.draft')!))
  expect(stored.login.providers.github).toEqual({ enabled: true })
  expect(stored.login).not.toHaveProperty('pendingIdentityHours')
  expect(stored.login).not.toHaveProperty('identityBindingEnabled')
  await page.reload()
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'GitHub Quick login', exact: true })).toBeChecked()
  await page.getByRole('switch', { name: 'GitHub Quick login', exact: true }).uncheck()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'GitHub Quick login', exact: true })).toBeChecked()
})

test('agreement header actions keep document editing separate from page save', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Login agreement', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Login agreement', exact: true }).click()
  await page.getByRole('button', { name: 'Checkbox', exact: true }).click()
  expect(await page.evaluate(() => sessionStorage.getItem('ovload.general-settings.draft'))).toBeNull()
  const add = page.getByRole('button', { name: 'Add document', exact: true })
  await add.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Document title', { exact: true }).fill('Preview document')
  await dialog.getByLabel('Route slug', { exact: true }).fill('preview-document')
  await dialog.getByLabel('Content (Markdown)', { exact: true }).fill('Preview content')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(add).toBeFocused()
  await expect(page.getByRole('heading', { name: 'Preview document', exact: true })).toHaveCount(0)
  await add.click()
  await dialog.getByLabel('Document title', { exact: true }).fill('Preview document')
  await dialog.getByLabel('Route slug', { exact: true }).fill('preview-document')
  await dialog.getByLabel('Content (Markdown)', { exact: true }).fill('Preview content')
  await dialog.getByRole('button', { name: 'Add document', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('heading', { name: 'Preview document', exact: true })).toBeVisible()
  await save(page).click()
  await expect(save(page)).toBeDisabled()
  const agreement = await page.evaluate(() => JSON.parse(sessionStorage.getItem('ovload.general-settings.draft')!).agreement)
  expect(agreement.mode).toBe('checkbox')
  expect(agreement.documents).toHaveLength(5)
  expect(agreement.documents[4]).toMatchObject({ title: 'Preview document', slug: 'preview-document', content: 'Preview content' })
})

test('agreement errors select its tab and edits survive tab changes, save and discard', async ({ page }) => {
  const agreementTab = page.getByRole('tab', { name: 'Login agreement', exact: true })
  await agreementTab.click()
  await page.getByRole('switch', { name: 'Login agreement', exact: true }).click()
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await save(page).click()
  await expect(agreementTab).toHaveAttribute('aria-selected', 'true')
  const content = page.getByLabel('Content (Markdown)', { exact: true })
  await expect(content.first()).toBeFocused()
  await expect(content.first()).toHaveAttribute('aria-invalid', 'true')
  expect(await page.evaluate(() => sessionStorage.getItem('ovload.general-settings.draft'))).toBeNull()
  for (const field of await content.all()) await field.fill('Preview terms content')
  const title = page.getByLabel('Document title', { exact: true }).first()
  await title.fill('Preview terms')
  await page.getByRole('tab', { name: 'Register & login', exact: true }).click()
  await save(page).click()
  await expect(save(page)).toBeDisabled()
  await page.reload()
  await agreementTab.click()
  await expect(title).toHaveValue('Preview terms')
  await title.fill('Unsaved terms')
  await page.getByRole('button', { name: 'Discard changes', exact: true }).filter({ visible: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(title).toHaveValue('Preview terms')
})
