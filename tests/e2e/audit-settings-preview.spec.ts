for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
  test(`audit tab switches keep content stationary at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.reload()
    const panel = page.getByRole('tabpanel')
    const metrics = () => panel.evaluate((element) => {
      const scroll = element.parentElement!
      return { width: scroll.clientWidth, height: scroll.clientHeight, top: scroll.scrollTop }
    })
    const initial = await metrics()
    for (const name of ['Referral rebates', 'Security audit', 'Referral rebates', 'Security audit']) {
      await page.getByRole('tab', { name, exact: true }).click()
      await expect(page.getByRole('heading', { name, exact: true, level: 2 })).toBeVisible()
      const frames = await panel.evaluate(async (element) => {
        const scroll = element.parentElement!
        const heading = element.querySelector('h2')!
        const samples: { x: number; y: number; width: number; scrollWidth: number }[] = []
        const start = performance.now()
        while (performance.now() - start < 250) {
          await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()))
          const rect = heading.getBoundingClientRect()
          const container = scroll.getBoundingClientRect()
          samples.push({ x: rect.x - container.x, y: rect.y - container.y,
            width: scroll.clientWidth, scrollWidth: scroll.scrollWidth })
        }
        return samples
      })
      for (const frame of frames) {
        expect(Math.abs(frame.x)).toBeLessThan(0.5)
        expect(Math.abs(frame.y)).toBeLessThan(0.5)
        expect(frame.width).toBe(initial.width)
        expect(frame.scrollWidth).toBe(frame.width)
      }
      expect((await metrics()).height).toBe(initial.height)
      // Exercise the next switch from the bottom of a long audit form.
      await panel.evaluate((element) => {
        element.parentElement!.scrollTop = element.parentElement!.scrollHeight
      })
    }
    await page.getByRole('tab', { name: 'Security audit', exact: true }).focus()
    await page.keyboard.press(viewport.width < 768 ? 'ArrowRight' : 'ArrowDown')
    await expect(page.getByRole('tab', { name: 'Referral rebates', exact: true })).toBeFocused()
    await expect(page.getByRole('heading', { name: 'Referral rebates', exact: true })).toBeVisible()
    expect((await metrics()).top).toBe(0)
    expect(await page.evaluate(() => window.scrollY)).toBe(0)
  })
}


