async function removeScopeGroup(page: Page, name: string) {
  await page.getByTestId('audit-scope').getByRole('button', { name: 'Remove ' + name, exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Remove from draft', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeHidden()
  await expect(page.getByTestId('audit-scope').getByRole('table')).toBeVisible()
}
async function clearScope(page: Page) {
  const scope = page.getByTestId('audit-scope')
  while (await scope.getByRole('button', { name: /^Remove / }).count()) {
    await scope.getByRole('button', { name: /^Remove / }).first().click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Remove from draft', exact: true }).click()
    await expect(page.getByRole('alertdialog')).toBeHidden()
    await expect(scope.getByRole('table')).toBeVisible()
  }
}
