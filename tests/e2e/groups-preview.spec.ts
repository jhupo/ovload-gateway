import { mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from '../../web/node_modules/@playwright/test'

const captures = join(tmpdir(), 'ovload-groups-scroll-20260930')
for (const mobile of [false, true]) {
  for (const theme of ['light','dark'] as const) {
    test(`groups ${mobile ? 'mobile' : 'desktop'} ${theme}`, async ({ page }) => {
      test.setTimeout(120_000)
      await mkdir(captures, { recursive: true })
      await page.setViewportSize(mobile ? { width:390,height:844 } : { width:1440,height:900 })
      await page.emulateMedia({ colorScheme:theme, reducedMotion:'reduce' })
      await page.addInitScript(() => { localStorage.setItem('i18nextLng','zh'); sessionStorage.setItem('ovload.admin-preview','active') })
      const errors: string[] = [], writes: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('request', request => { if (['POST','PATCH','PUT','DELETE'].includes(request.method())) writes.push(request.url()) })
      const capture = async (state: string) => {
        await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))) })
        await page.screenshot({ path:join(captures,`${mobile ? 'mobile' : 'desktop'}-${theme}-${state}.png`) })
      }
      await page.goto('/groups')
      const rows = page.getByTestId('group-row')
      await expect(rows).toHaveCount(10)
      await expect(page.getByRole('columnheader')).toHaveCount(9)
      await capture('table')
      const scroller = page.getByTestId('groups-table-viewport').locator('[data-slot="table-container"]')
      if (mobile) {
        await scroller.evaluate(el => { el.scrollLeft = 350 })
        await capture('table-middle')
        await scroller.evaluate(el => { el.scrollLeft = el.scrollWidth })
        await capture('table-actions')
      }
      const edit = page.getByRole('button',{name:'编辑 OpenAI Standard',exact:true})
      await edit.click()
      const dialog = page.getByRole('dialog')
      await expect(dialog.getByRole('button',{name:'保存',exact:true})).toBeDisabled()
      await capture('general')
      await dialog.getByLabel('名称',{exact:true}).fill('Draft group')
      await page.keyboard.press('Escape')
      await expect(dialog).toBeVisible()
      await expect(dialog.getByRole('tab')).toHaveCount(0)
      const editor = page.getByTestId('group-editor-body')
      await editor.hover()
      await page.mouse.wheel(0, 250)
      await expect.poll(() => editor.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
      await dialog.getByRole('heading',{name:'计费',exact:true}).evaluate(el => el.scrollIntoView({block:'start'}))
      await capture('billing-off')
      for (const name of ['图片单独计费','高低峰计费','网页搜索单独计费']) await dialog.getByRole('switch',{name,exact:true}).click()
      await dialog.getByRole('heading',{name:'计费',exact:true}).evaluate(el => el.scrollIntoView({block:'start'}))
      await capture('billing-top')
      await dialog.getByLabel('搜索单价 (OVL / 次)',{exact:true}).fill('0.025')
      const editorBottom = (await page.getByTestId('group-editor-body').boundingBox())!
      const searchPrice = (await dialog.getByLabel('搜索单价 (OVL / 次)',{exact:true}).boundingBox())!
      expect(searchPrice.y + searchPrice.height).toBeLessThanOrEqual(editorBottom.y + editorBottom.height)
      await capture('billing-bottom')
      await dialog.getByRole('heading',{name:'模型计价',exact:true}).evaluate(el => el.scrollIntoView({block:'start'}))
      await expect(dialog.getByTestId('model-price')).toHaveCount(1)
      await capture('model-prices')
      await dialog.getByRole('button',{name:'移除模型计价 1',exact:true}).click()
      await capture('model-empty')
      await dialog.getByRole('button',{name:'添加模型计价',exact:true}).click()
      await dialog.getByLabel('模型',{exact:true}).fill('custom-model')
      await dialog.getByLabel('输入 (OVL / 百万 Token)',{exact:true}).fill('1.5')
      await dialog.getByRole('heading',{name:'路由',exact:true}).evaluate(el => el.scrollIntoView({block:'start'}))
      await dialog.getByRole('combobox',{name:'Fast 模式',exact:true}).click()
      await page.getByRole('option',{name:'强制',exact:true}).click()
      await dialog.getByRole('switch',{name:'Live',exact:true}).click()
      await expect(dialog.getByRole('heading',{name:/^编辑分组/})).toBeInViewport({ratio:1})
      await expect(dialog.getByRole('button',{name:'取消',exact:true})).toBeInViewport({ratio:1})
      expect(await dialog.evaluate(el => el.scrollTop)).toBe(0)
      await capture('routing')
      await dialog.getByRole('button',{name:'添加映射',exact:true}).click()
      await expect(dialog.getByTestId('model-mapping')).toHaveCount(2)
      await dialog.getByRole('button',{name:'移除映射 2',exact:true}).click()
      await dialog.getByRole('button',{name:'取消',exact:true}).click()
      await expect(edit).toBeFocused()
      await edit.click()
      await expect(dialog.getByLabel('名称',{exact:true})).toHaveValue('OpenAI Standard')
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      const exclusive = page.getByRole('button',{name:'OpenAI Standard 的专属设置',exact:true})
      await exclusive.click()
      await dialog.getByRole('combobox',{name:'选择用户',exact:true}).click()
      const userList = page.locator('[data-slot=command-list]')
      await capture('user-selector-top')
      await userList.hover()
      await page.mouse.wheel(0, 500)
      await expect.poll(() => userList.evaluate(el => el.scrollTop)).toBeGreaterThan(100)
      await capture('user-selector-scrolled')
      await page.getByPlaceholder('搜索用户名或邮箱…').fill('mia')
      await capture('user-selector')
      await page.getByPlaceholder('搜索用户名或邮箱…').fill('no-such-user')
      await expect(page.getByText('无结果。',{exact:true})).toBeVisible()
      await capture('user-selector-empty')
      await page.getByPlaceholder('搜索用户名或邮箱…').fill('mia')
      await page.getByRole('option',{name:/mia.chen/}).click()
      await dialog.getByRole('button',{name:'添加专属设置',exact:true}).click()
      await expect(dialog.getByTestId('group-override')).toHaveCount(2)
      await dialog.getByLabel('mia.chen 费率倍率',{exact:true}).fill('0.6')
      await dialog.getByLabel('mia.chen 每分钟 RPM',{exact:true}).fill('180')
      await page.keyboard.press('Escape')
      await expect(dialog).toBeVisible()
      await dialog.getByRole('button',{name:'移除 mia.chen 的专属设置',exact:true}).click()
      await dialog.getByRole('button',{name:'移除 lin.zhou 的专属设置',exact:true}).click()
      await dialog.getByRole('button',{name:'取消',exact:true}).click()
      await expect(exclusive).toBeFocused()
      await page.getByRole('button',{name:'删除 OpenAI Standard',exact:true}).click()
      await expect(page.getByRole('alertdialog').getByRole('button',{name:'删除分组',exact:true})).toBeDisabled()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('alertdialog')).toBeVisible()
      await page.getByRole('alertdialog').getByRole('button',{name:'取消',exact:true}).click()
      const frame = await page.getByTestId('groups-table-viewport').boundingBox()
      await page.getByRole('button',{name:'下一页',exact:true}).click()
      await expect(rows).toHaveCount(4)
      expect(await page.getByTestId('groups-table-viewport').boundingBox()).toEqual(frame)
      await page.getByRole('button',{name:'状态',exact:true}).click()
      await page.getByRole('option',{name:/停用/}).click()
      await page.keyboard.press('Escape')
      await expect(rows).toHaveCount(1)
      await expect(rows).toContainText('无可用容量')
      await page.reload()
      await expect(rows).toHaveCount(1)
      await page.getByRole('button',{name:'重置',exact:true}).click()
      await expect(rows).toHaveCount(10)
      await page.getByRole('textbox',{name:'搜索分组名称…',exact:true}).fill('missing-group')
      await expect(rows).toHaveCount(0)
      await expect(page.getByText('无结果。',{exact:true})).toBeInViewport({ratio:1})
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect(errors).toEqual([])
      expect(writes).toEqual([])
      expect(await page.evaluate(() => JSON.stringify([localStorage,sessionStorage]))).not.toContain('Draft group')
    })
  }
}

test('groups navigation, English and keyboard scrolling', async ({ page }) => {
  await page.addInitScript(() => { localStorage.setItem('i18nextLng','en'); sessionStorage.setItem('ovload.admin-preview','active') })
  await page.goto('/users')
  await page.getByRole('link',{name:'Groups',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Groups',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Edit OpenAI Standard',exact:true}).click()
  await expect(page.getByRole('tab')).toHaveCount(0)
  await expect(page.getByLabel('Name', {exact:true})).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Description', {exact:true})).toBeFocused()
  const targetModel = page.getByLabel('Target model',{exact:true})
  await targetModel.focus()
  await expect(targetModel).toBeInViewport({ratio:1})
  expect(await page.getByTestId('group-editor-body').evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button',{name:'Edit OpenAI Standard',exact:true})).toBeFocused()
})
