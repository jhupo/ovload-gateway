for (const mobile of [false, true]) {
  for (const theme of ['light', 'dark'] as const) {
    test(`monitor model entry ${mobile ? 'mobile' : 'desktop'} ${theme}`, async ({ page }) => {
      await mkdir(captures, { recursive: true })
      await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.addInitScript(() => {
        localStorage.setItem('i18nextLng', 'zh')
        sessionStorage.setItem('ovload.admin-preview', 'active')
      })
      const errors: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      const shot = async (state: string) => page.screenshot({ path: resolve(captures, `models-${mobile ? 'mobile' : 'desktop'}-${theme}-${state}.png`), animations: 'disabled' })
      await page.goto('/channels/monitoring')
      const trigger = page.getByRole('button', { name: '为 OpenAI 添加模型', exact: true })
      await expect(trigger).toBeVisible({ timeout: 30000 })
      await trigger.scrollIntoViewIfNeeded()
      await shot('default')
      await trigger.click()
      const popup = page.getByRole('dialog', { name: '为 OpenAI 添加模型', exact: true })
      await expect(popup.getByRole('textbox', { name: '模型名称' })).toBeFocused()
      await shot('open')
      await popup.getByRole('button', { name: '添加模型', exact: true }).click()
      await expect(popup.getByRole('alert')).toContainText('请输入')
      await shot('invalid')
      await popup.getByRole('textbox').fill('gpt-5')
      await popup.getByRole('button', { name: '添加模型', exact: true }).click()
      await expect(popup.getByRole('alert')).toHaveText('该模型已存在。')
      await shot('duplicate')
      await popup.getByRole('textbox').fill('  custom-model-preview  ')
      await popup.getByRole('textbox').press('Enter')
      await expect(popup).not.toBeVisible()
      await expect(trigger).toBeFocused()
      const model = page.getByRole('checkbox', { name: 'custom-model-preview', exact: true })
      await expect(model).toBeChecked()
      await shot('added')
      await model.uncheck()
      await expect(model).not.toBeChecked()
      await expect(model).toBeVisible()
      await page.getByRole('button', { name: '保存', exact: true }).last().click()
      await model.check()
      await page.getByRole('button', { name: '重置', exact: true }).click()
      await expect(model).not.toBeChecked()
      await trigger.click()
      await popup.getByRole('textbox').fill('unsaved-model')
      await popup.getByRole('textbox').press('Escape')
      await expect(trigger).toBeFocused()
      await trigger.click()
      await expect(popup.getByRole('textbox')).toHaveValue('')
      await popup.getByRole('button', { name: '取消', exact: true }).click()
      await expect(popup).not.toBeVisible()
      await expect(trigger).toBeFocused()
      await page.getByRole('spinbutton', { name: '缓存率异常', exact: true }).scrollIntoViewIfNeeded()
      await page.mouse.move(mobile ? 380 : 1420, 700)
      await page.mouse.wheel(0, 900)
      await expect.poll(async () => (await page.getByRole('banner').boundingBox())?.y).toBe(0)
      await shot('sticky')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      expect(errors).toEqual([])
    })
  }
}
