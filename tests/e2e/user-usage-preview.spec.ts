import { expect, test } from '../../web/node_modules/@playwright/test'

test.use({ hasTouch: true })

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('ovload.admin-preview', 'active')
    localStorage.setItem('i18nextLng', 'en')
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
})

test('personal usage agrees with dashboard, filters summaries and paginates bounded records', async ({ page }) => {
  const writes: string[] = []
  page.on('request', (request) => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()) })
  await page.goto('/user/dashboard')
  await page.getByRole('link', { name: 'View all usage', exact: true }).click()
  await expect(page).toHaveURL(/\/user\/usage$/)
  const total = await page.getByTestId('usage-total-requests').innerText()
  const table = page.getByRole('table', { name: 'Usage history', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  const second = await table.locator('tbody tr').first().getAttribute('data-usage-id')
  await page.getByRole('combobox', { name: 'Time range', exact: true }).click()
  await page.getByRole('option', { name: 'Last 30 days', exact: true }).click()
  await expect(page.getByTestId('usage-total-requests')).not.toHaveText(total)
  await expect(page.getByRole('button', { name: 'Previous page', exact: true })).toBeDisabled()
  await expect(table.locator('tbody tr').first()).not.toHaveAttribute('data-usage-id', second!)
  await page.getByRole('button', { name: 'Model', exact: true }).and(page.locator('[aria-haspopup=dialog]')).click()
  await page.getByRole('option', { name: /claude-sonnet-4-6/ }).click()
  await page.keyboard.press('Escape')
  await expect(table.locator('tbody tr').first()).toContainText('claude-sonnet-4-6')
  await page.getByRole('button', { name: 'API key', exact: true }).click()
  await page.getByRole('option', { name: /CLI/ }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Status', exact: true })).toHaveCount(0)
  await expect(table).not.toContainText('Failed')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByRole('combobox', { name: 'Rows per page', exact: true }).click()
  await page.getByRole('option', { name: '50', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(50)
  await page.getByRole('textbox', { name: 'Search model or key…', exact: true }).fill('no-such-record')
  await expect(table).toContainText('No results')
  await expect(page.getByTestId('usage-total-requests')).toHaveText('0')
  await expect(page.getByTestId('usage-total-averageDuration')).toHaveText('—')
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled()
  expect(writes).toEqual([])
})

test('column visibility, sorting and safe hover/focus breakdowns without request actions', async ({ page }) => {
  await page.goto('/user/usage')
  const table = page.getByRole('table', { name: 'Usage history', exact: true })
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await expect(page.getByRole('menuitemcheckbox', { name: 'Request ID', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitemcheckbox', { name: 'Billing source', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitemcheckbox', { name: 'Endpoints', exact: true })).toBeChecked()
  await page.getByRole('menuitemcheckbox', { name: 'Reasoning effort', exact: true }).click()
  await expect(page.getByRole('menuitemcheckbox', { name: 'Status', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitemcheckbox', { name: 'Input tokens', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitemcheckbox', { name: 'Output tokens', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(table.getByRole('columnheader', { name: 'Reasoning effort', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitemcheckbox', { name: 'Reasoning effort', exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Reasoning effort', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menuitemcheckbox', { name: 'Reasoning effort', exact: true })).toBeHidden()
  await expect(table.getByRole('columnheader', { name: 'Reasoning effort', exact: true })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: 'Request type', exact: true })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: 'Request ID', exact: true })).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: 'Billing source', exact: true })).toHaveCount(0)
  await expect(table).toContainText('Generation')
  await expect(table).toContainText('Compaction')
  await expect(table).toContainText('Search')
  await expect(table).toContainText('Streaming')
  await expect(table).toContainText('WS')
  await expect(table).not.toContainText('Non-streaming')
  await expect(table).toContainText('High')
  await expect(table).toContainText('Medium')
  await expect(table).toContainText('Low')
  await expect(table.getByRole('button', { name: 'Token breakdown', exact: true }).first().locator('dt')).toHaveText(['Input', 'Output', 'Cache'])
  const headers = await table.getByRole('columnheader').allTextContents()
  const requestTypeIndex = headers.indexOf('Request type')
  const endpointIndex = headers.indexOf('Endpoints')
  expect(requestTypeIndex).toBeGreaterThanOrEqual(0)
  expect(endpointIndex).toBeGreaterThanOrEqual(0)
  const modePositions: number[] = []
  for (const row of await table.locator('tbody tr').all()) {
    const type = row.locator('td').nth(requestTypeIndex)
    const badge = await type.locator('[data-slot=badge]').boundingBox()
    if (await type.locator('[data-slot=badge] > span:not([aria-hidden])').textContent() === 'Compaction') {
      await expect(type.getByText(/^(Streaming|WS)$/)).toHaveCount(0)
      continue
    }
    const mode = await type.getByText(/^(Streaming|WS)$/).boundingBox()
    expect(Math.abs(badge!.y + badge!.height / 2 - mode!.y - mode!.height / 2)).toBeLessThan(1)
    expect(mode!.x).toBeGreaterThan(badge!.x + badge!.width)
    modePositions.push(mode!.x)
  }
  expect(Math.max(...modePositions) - Math.min(...modePositions)).toBeLessThan(1)
  const converted = table.locator('tbody tr').nth(1).locator('td').nth(endpointIndex)
  await expect(converted.locator('dt')).toHaveText(['Inbound', 'Outbound'])
  await expect(converted.locator('dd')).toHaveText(['/v1/chat/completions', '/v1/responses'])
  await table.getByRole('button', { name: 'Charge', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Desc', exact: true }).click()
  const first = table.locator('tbody tr').first()
  const id = await first.getAttribute('data-usage-id')
  await expect(table.getByRole('columnheader')).toHaveCount(10)
  await expect(page.getByRole('button', { name: /Request details/ })).toHaveCount(0)
  await first.getByRole('button', { name: 'Token breakdown', exact: true }).hover()
  const detail = page.getByRole('tooltip')
  await expect(detail).toContainText('Cached input tokens')
  await expect(detail).toContainText('Cache write tokens')
  await page.keyboard.press('Escape')
  await expect(detail).toHaveCount(0)
  await first.getByRole('button', { name: 'Billing breakdown', exact: true }).focus()
  await expect(detail).toContainText('Input charge')
  await expect(detail).toContainText('Output charge')
  await expect(detail).toContainText('Cache read charge')
  await expect(detail).toContainText('Input unit price')
  await expect(detail).toContainText('Output unit price')
  await expect(detail).toContainText('Service tier')
  await expect(detail).toContainText('Multiplier')
  await expect(detail).toContainText('Base charge')
  await expect(detail).toContainText('User charge')
  await expect(detail).toContainText(/OVL \d+\.\d{6}/)
  const billingColumns = await page.locator('[data-slot=tooltip-content] > div').first().locator('dd').evaluateAll((elements) => elements.map((element) => element.getBoundingClientRect().right))
  expect(Math.max(...billingColumns) - Math.min(...billingColumns)).toBeLessThan(1)
  await expect(detail).not.toContainText('USD')
  await expect(detail).not.toContainText('Upstream account')
  await page.keyboard.press('Escape')
  await expect(detail).toHaveCount(0)
  await first.getByRole('button', { name: 'Connection details', exact: true }).hover()
  await expect(detail).toContainText('Request IP')
  await expect(detail).toContainText('Connection latency')
  await expect(detail).toContainText('User-Agent')
  await expect(detail).toContainText(/PreviewCLI|PreviewClient/)
  await page.keyboard.press('Escape')
  await expect(detail).toHaveCount(0)
  await expect(first).toContainText('Cache hit rate')
  const search = page.getByRole('textbox', { name: 'Search model or key…', exact: true })
  await search.fill(id!)
  await expect(table).toContainText('No results')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await search.fill('gpt-5.4')
  await expect(table.locator('tbody tr').first()).toContainText('gpt-5.4')
})

test('mobile keeps filters, table scroll and tap breakdowns usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/user/usage')
  await expect(page.getByRole('heading', { name: 'Usage history', exact: true })).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const scroller = page.getByTestId('usage-viewport').locator('[data-slot=table-container]')
  await scroller.evaluate((element) => { element.scrollLeft = element.scrollWidth })
  await page.getByRole('button', { name: 'Connection details', exact: true }).first().tap()
  const detail = page.locator('[data-slot=tooltip-content]')
  await expect(detail).toBeVisible()
  await expect.poll(() => detail.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(detail).not.toBeVisible()
  const charge = page.getByRole('button', { name: 'Billing breakdown', exact: true }).first()
  await charge.evaluate((element) => element.scrollIntoView({ inline: 'center', block: 'nearest' }))
  await charge.tap()
  await expect(detail).toBeVisible()
  await expect(detail).toContainText('Cache read charge')
  await expect.poll(() => detail.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  const bounds = await detail.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.keyboard.press('Escape')
  await expect(detail).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Status', exact: true })).toHaveCount(0)
  await expect(page.getByTestId('user-workspace-header').getByRole('button', { name: 'Toggle theme', exact: true })).toBeVisible()
})
