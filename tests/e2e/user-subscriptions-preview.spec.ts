import { expect, test } from '../../web/node_modules/@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('ovload.admin-preview', 'active')
    localStorage.setItem('i18nextLng', 'en')
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
})

test('owned plans show bounded quotas, purchased details and read-only history', async ({ page }) => {
  const writes: string[] = []
  page.on('request', (request) => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()) })
  await page.goto('/user/subscriptions')
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'My subscriptions', exact: true })).toHaveAttribute('data-state', 'active')
  await expect(page.getByText('Sample data', { exact: true })).toBeVisible()
  await expect(page.getByTestId('owned-subscription')).toHaveCount(2)
  const pro = page.getByTestId('owned-subscription').filter({ hasText: 'DEMO-SUB-001' })
  await expect(pro).toContainText('Pro')
  await expect(pro).toContainText('CNY 59.00')
  await expect(page.getByRole('progressbar', { name: 'Gemini Dev · Daily quota', exact: true })).toHaveAttribute('aria-valuenow', '100')
  await expect(page.getByTestId('owned-subscription').filter({ hasText: 'Gemini Dev' })).toContainText('Unlimited')
  await pro.getByRole('button', { name: 'Subscription details · DEMO-SUB-001', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('DEMO-SUB-001')
  await expect(page.getByRole('dialog')).toContainText('OVL 200.00')
  await page.keyboard.press('Escape')
  await expect(pro.getByRole('button', { name: 'Subscription details · DEMO-SUB-001', exact: true })).toBeFocused()
  await page.getByRole('tab', { name: /Subscription history/ }).click()
  const table = page.getByRole('table', { name: 'Subscription history', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(6)
  await page.getByRole('textbox', { name: 'Search plan or subscription ID…' }).fill('DEMO-SUB-005')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('Terminated')
  await table.getByRole('button', { name: 'Subscription details · DEMO-SUB-005' }).click()
  await expect(page.getByRole('dialog')).toContainText('Terminated')
  await page.getByRole('dialog').locator('[data-slot=dialog-footer]').getByRole('button', { name: 'Close', exact: true }).click()
  await expect(table.getByRole('button', { name: 'Subscription details · DEMO-SUB-005' })).toBeFocused()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByRole('button', { name: 'Status', exact: true }).click()
  await page.getByRole('option', { name: /Expired/ }).click()
  await page.keyboard.press('Escape')
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Subscription ID', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(table.getByRole('columnheader', { name: 'Subscription ID', exact: true })).toBeVisible()
  await table.getByRole('button', { name: 'Expires (UTC)', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Asc', exact: true }).click()
  await expect(table.locator('tbody tr').first()).toContainText('DEMO-SUB-008')
  await page.getByRole('textbox', { name: 'Search plan or subscription ID…' }).fill('no-such-subscription')
  await expect(table).toContainText('No results')
  expect(writes).toEqual([])
})

test('settings tabs route consistently and protect unsaved profile changes', async ({ page }) => {
  await page.goto('/user/settings')
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill('Unsaved profile')
  await page.getByRole('tab', { name: 'My subscriptions', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page).toHaveURL(/\/user\/settings$/)
  await expect(page.getByRole('textbox', { name: 'Username', exact: true })).toHaveValue('Unsaved profile')
  await page.getByRole('tab', { name: 'My subscriptions', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page).toHaveURL(/\/user\/subscriptions$/)
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Profile', exact: true }).click()
  await expect(page).toHaveURL(/\/user\/settings$/)
  await expect(page.getByRole('textbox', { name: 'Username', exact: true })).toHaveValue('alex')
  await page.goto('/user/dashboard')
  await page.getByRole('link', { name: 'View all subscriptions', exact: true }).click()
  await expect(page).toHaveURL(/\/user\/subscriptions$/)
})

test('mobile keeps current plans and historical tables inside the settings content', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/user/subscriptions')
  await expect(page.getByTestId('owned-subscription')).toHaveCount(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.getByTestId('owned-subscription').evaluateAll((cards) => cards.every((card) => card.scrollWidth <= card.clientWidth))).toBe(true)
  await page.getByRole('tab', { name: /Subscription history/ }).click()
  await expect(page.getByRole('table', { name: 'Subscription history', exact: true }).locator('tbody tr')).toHaveCount(6)
  const scroller = page.getByTestId('subscription-history').locator('[data-slot=table-container]')
  await scroller.evaluate((element) => { element.scrollLeft = element.scrollWidth })
  await page.getByRole('button', { name: 'Subscription details · DEMO-SUB-003', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').locator('[data-slot=dialog-footer]').getByRole('button', { name: 'Close', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
