import { expect, test, type Page } from '../../web/node_modules/@playwright/test'

const key = 'ovload.lottery.rounds.preview'
const start = (page: Page) => page.getByRole('button', { name: 'Start lottery', exact: true })
const editor = (page: Page) => page.getByRole('dialog', { name: 'Start lottery', exact: true })
const managed = (page: Page) => page.getByTestId('lottery-managed-round')
const tab = (page: Page) => page.getByRole('tab', { name: 'Lottery', exact: true }).click()
const submit = (page: Page) => editor(page).getByRole('button', { name: 'Start preview', exact: true }).click()
async function confirmStart(page: Page) { await start(page).click(); await submit(page); await expect(editor(page)).toHaveCount(0) }
async function failStorage(page: Page) {
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    ;(window as unknown as { restoreRoundStorage: () => void }).restoreRoundStorage = () => { Storage.prototype.setItem = original }
    Storage.prototype.setItem = function (key, value) {
      if (key === 'ovload.lottery.rounds.preview') throw new DOMException('Blocked', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
}
const restoreStorage = (page: Page) => page.evaluate(() => (window as unknown as { restoreRoundStorage: () => void }).restoreRoundStorage())

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => { sessionStorage.setItem('ovload.admin-preview', 'active'); localStorage.setItem('i18nextLng', 'en') })
  await page.goto('/page-settings')
  await tab(page)
})

test('rules live only in the start dialog and confirmed creation persists the public round', async ({ page }) => {
  const mutations: string[] = []
  page.on('request', request => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method())) mutations.push(request.url()) })
  await expect(page.getByLabel('Reward per winner (OVL)', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toHaveCount(0)
  await start(page).click()
  await expect(editor(page)).toContainText('Local preview')
  await editor(page).getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(start(page)).toBeFocused()
  expect(await page.evaluate(key => sessionStorage.getItem(key), key)).toBeNull()
  await start(page).click()
  await editor(page).getByLabel('Reward per winner (OVL)', { exact: true }).fill('8.25')
  await editor(page).getByLabel('Participants to draw', { exact: true }).fill('80')
  await submit(page)
  await expect(managed(page)).toContainText('Round #167')
  await expect(start(page)).toBeDisabled()
  await expect(page.getByRole('button', { name: 'End activity', exact: true })).toBeFocused()
  await page.reload(); await tab(page)
  await expect(managed(page)).toContainText('Round #167')
  await page.getByRole('switch', { name: 'Lottery page', exact: true }).check()
  await page.getByRole('link', { name: 'Lottery', exact: true }).click()
  await expect(page.getByTestId('lottery-current')).toContainText('OVL 8.25')
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '0')
  await expect(page.getByRole('button', { name: 'Join lottery', exact: true })).toBeDisabled()
  expect(mutations).toEqual([])
})

test('ending requires confirmation, preserves winners and enables the next round', async ({ page }) => {
  await confirmStart(page)
  const records = page.getByRole('table', { name: 'Winning users by round', exact: true })
  const previous = await records.innerText()
  await page.getByRole('button', { name: 'End activity', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(managed(page)).toContainText('Round #167')
  await page.getByRole('button', { name: 'End activity', exact: true }).click()
  await failStorage(page)
  await page.getByRole('alertdialog').getByRole('button', { name: 'End activity', exact: true }).click()
  await expect(page.getByText('Unable to save the activity. Check browser storage permissions', { exact: true })).toBeVisible()
  await expect(managed(page)).toContainText('Round #167')
  await restoreStorage(page)
  await page.getByRole('alertdialog').getByRole('button', { name: 'End activity', exact: true }).click()
  await expect(start(page)).toBeFocused()
  expect(await records.innerText()).toBe(previous)
  await page.getByRole('switch', { name: 'Lottery page', exact: true }).check()
  await page.getByRole('link', { name: 'Lottery', exact: true }).click()
  await expect(page.getByTestId('lottery-current')).toContainText('No active lottery')
  await expect(page.getByRole('progressbar')).toHaveCount(0)
  await page.goto('/page-settings'); await tab(page); await confirmStart(page)
  await expect(managed(page)).toContainText('Round #168')
})

test('invalid rules focus the field and failed creation rolls back defaults and can retry', async ({ page }) => {
  await start(page).click()
  const reward = editor(page).getByLabel('Reward per winner (OVL)', { exact: true })
  await reward.fill('0.001'); await submit(page)
  await expect(reward).toBeFocused()
  await reward.fill('6')
  await failStorage(page); await submit(page)
  await expect(page.getByText('Unable to save the activity. Check browser storage permissions', { exact: true })).toBeVisible()
  await expect(editor(page)).toBeVisible()
  expect(await page.evaluate(key => sessionStorage.getItem(key), key)).toBeNull()
  expect(await page.evaluate(() => sessionStorage.getItem('ovload.lottery.draft'))).toBeNull()
  await restoreStorage(page); await submit(page)
  await expect(managed(page)).toContainText('Round #167')
})

test('dirty dialog requires an explicit discard decision on Escape, outside click and close', async ({ page }) => {
  await start(page).click()
  const reward = editor(page).getByLabel('Reward per winner (OVL)', { exact: true })
  await reward.fill('6')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(reward).toHaveValue('6')
  await page.mouse.click(5, 5)
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Keep editing', exact: true }).click()
  await editor(page).getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(editor(page)).toHaveCount(0)
  await expect(start(page)).toBeFocused()
  await start(page).click()
  await expect(editor(page).getByLabel('Reward per winner (OVL)', { exact: true })).toHaveValue('5.00')
  expect(await page.evaluate(key => sessionStorage.getItem(key), key)).toBeNull()
})

test('malformed activity bytes remain until explicit start and visibility stays independent', async ({ page }) => {
  await page.evaluate(key => sessionStorage.setItem(key, '{'), key)
  await page.reload(); await tab(page)
  await expect(page.getByText('The stored activity could not be loaded. Stored data has been preserved.', { exact: true })).toBeVisible()
  expect(await page.evaluate(key => sessionStorage.getItem(key), key)).toBe('{')
  await confirmStart(page)
  await expect(managed(page)).toContainText('Round #167')
  await expect(page.getByRole('switch', { name: 'Lottery page', exact: true })).not.toBeChecked()
})

test('winners table searches identities, filters rounds, sorts, paginates and controls columns', async ({ page }) => {
  const section = page.getByTestId('lottery-winners')
  const table = section.getByRole('table', { name: 'Winning users by round', exact: true })
  await expect(table.getByRole('row')).toHaveCount(11)
  await expect(table.getByRole('row').nth(1)).toContainText('sample_01')
  await expect(table.getByRole('row').nth(1)).toContainText('winner01@example.com')
  await section.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(table.getByRole('row').nth(1)).toContainText('sample_11')
  const search = section.getByRole('textbox', { name: 'Search username, email or round', exact: true })
  await search.fill('winner20@example.com')
  await expect(table.getByRole('row').nth(1)).toContainText('sample_20')
  await section.getByRole('button', { name: 'Round', exact: true }).and(section.locator('[data-slot="popover-trigger"]')).click()
  await page.getByRole('option', { name: /Round #165/ }).click()
  await page.keyboard.press('Escape')
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(table.getByRole('row').nth(1)).toContainText('#165')
  await search.fill('missing')
  await expect(table).toContainText('No matching winning records')
  await section.getByRole('button', { name: 'Reset', exact: true }).click()
  await table.getByRole('columnheader', { name: 'Round', exact: true }).getByRole('button').click()
  await page.getByRole('menuitem', { name: 'Asc', exact: true }).click()
  await expect(table.getByRole('row').nth(1)).toContainText('#151')
  await section.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Drawn at', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(table.getByRole('columnheader', { name: 'Drawn at', exact: true })).toHaveCount(0)
})

