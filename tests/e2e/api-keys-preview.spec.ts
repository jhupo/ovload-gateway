test('use-key configurations and CCS links follow the selected group without mutating records', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (value: string) => { document.documentElement.dataset.copied = value } } }))
  await page.goto('/user/api-keys')
  const dialog = page.getByRole('dialog')
  const cases = [
    { name: 'Workspace', client: 'Codex CLI', app: 'codex', endpoint: 'https://api.example.com/v1', variable: 'OVLOAD_API_KEY' },
    { name: 'CLI', client: 'Claude Code', app: 'claude', endpoint: 'https://api.example.com', variable: 'ANTHROPIC_AUTH_TOKEN' },
    { name: 'Gemini Studio', client: 'Gemini CLI', app: 'gemini', endpoint: 'https://api.example.com', variable: 'GEMINI_API_KEY' },
  ]
  for (const item of cases) {
    const trigger = page.getByRole('button', { name: `Key actions · ${item.name}`, exact: true })
    await trigger.click()
    await page.getByRole('menuitem', { name: 'Use key', exact: true }).click()
    await expect(dialog).toContainText(item.client)
    await dialog.getByRole('tab', { name: 'PowerShell', exact: true }).click()
    await dialog.getByRole('button', { name: 'Copy · PowerShell', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-copied', new RegExp(`\\$env:${item.variable}='ovload-demo-`))
    await dialog.getByRole('tab', { name: 'CMD', exact: true }).click()
    await dialog.getByRole('button', { name: 'Copy · CMD', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-copied', new RegExp(`set "${item.variable}=ovload-demo-`))
    if (item.app === 'codex') {
      await dialog.getByRole('button', { name: 'Copy · %USERPROFILE%\\.codex\\config.toml', exact: true }).click()
      await expect(page.locator('html')).toHaveAttribute('data-copied', /env_key = "OVLOAD_API_KEY"/)
    }
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(trigger).toBeFocused()
    await trigger.click()
    await page.getByRole('menuitem', { name: 'Export to CCS', exact: true }).click()
    await expect(dialog).toContainText(item.client)
    const link = dialog.getByRole('link', { name: 'Open CCS', exact: true })
    const href = await link.getAttribute('href')
    const parameters = new URL(href!).searchParams
    expect(parameters.get('app')).toBe(item.app)
    expect(parameters.get('endpoint')).toBe(item.endpoint)
    expect(parameters.get('apiKey')).toMatch(/^ovload-demo-[a-f0-9-]{36}$/)
    expect(parameters.has('usageScript')).toBe(false)
    await dialog.getByRole('button', { name: 'Copy import link', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-copied', href!)
    // Do not invoke an installed desktop handler in browser automation.
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
  }
  await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(6)
})

test('mobile connection dialogs remain bounded, support keyboard tabs and report copy failures', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new Error('denied')) } }))
  await page.goto('/user/api-keys')
  const trigger = page.getByRole('button', { name: 'Key actions · Workspace', exact: true })
  await trigger.click()
  await page.getByRole('menuitem', { name: 'Use key', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: 'macOS / Linux', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByRole('tab', { name: 'PowerShell', exact: true })).toHaveAttribute('aria-selected', 'true')
  await dialog.getByRole('button', { name: 'Copy · PowerShell', exact: true }).click()
  await expect(page.getByText('Could not copy. Check clipboard permissions.')).toBeVisible()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
  await dialog.getByRole('button', { name: 'Close', exact: true }).first().click()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.getByRole('menuitem', { name: 'Export to CCS', exact: true }).click()
  await expect(dialog.getByRole('link', { name: 'Open CCS', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Copy import link', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.mouse.click(4, 4)
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
})
