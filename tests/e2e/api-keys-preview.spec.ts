test('copy feedback stays at the viewport corner and clears mobile fixed actions', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => {} } }))
  for (const width of [1440, 650, 390, 768]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/user/api-keys')
    await page.getByRole('button', { name: 'Copy sample endpoint', exact: true }).click()
    await expect(page.locator('[data-sonner-toaster]')).toHaveCount(1)
    const notification = page.locator('[data-sonner-toast]').first()
    await expect(notification).toBeVisible()
    await expect.poll(() => notification.evaluate(element => {
      const bounds = element.getBoundingClientRect()
      return { bottom: Math.round(innerHeight - bounds.bottom), right: Math.round(innerWidth - bounds.right) }
    })).toEqual({ bottom: width < 768 ? 80 : 24, right: width <= 600 ? 16 : 24 })
  }
})

