test('sample lifecycle validates, preserves edits, confirms mutations and resets on reload', async ({ page }) => {
  const writes: string[] = []
  page.on('request', (request) => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()) })
  await page.goto('/user/api-keys')
  await page.getByRole('button', { name: 'Create key', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Create key', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: 'Name', exact: true })).toBeFocused()
  await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Local client')
  await dialog.getByRole('textbox', { name: /Quota \(OVL/ }).fill('0.00001')
  await dialog.getByRole('button', { name: 'Create key', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: /Quota \(OVL/ })).toBeFocused()
  await dialog.getByRole('textbox', { name: /Quota \(OVL/ }).fill('12.3401')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('Local client')
  await dialog.getByRole('button', { name: 'Create key', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const row = page.getByRole('table').getByRole('row').filter({ hasText: 'Local client' })
  await expect(row).toContainText('Active')
  await row.getByRole('button', { name: 'Key actions · Local client' }).click()
  await page.getByRole('menuitem', { name: 'Edit key', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: 'Name', exact: true })).toBeFocused()
  await expect(dialog.getByRole('textbox', { name: /Quota \(OVL/ })).toHaveValue('12.3401')
  await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Local client edited')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  const editedRow = page.getByRole('table').getByRole('row').filter({ hasText: 'Local client edited' })
  await editedRow.getByRole('button', { name: 'Key actions · Local client edited' }).click()
  await page.getByRole('menuitem', { name: 'Disable', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Disable', exact: true }).click()
  await expect(editedRow).toContainText('Disabled')
  await expect(editedRow.getByRole('button', { name: 'Key actions · Local client edited' })).toBeFocused()
  await editedRow.getByRole('button', { name: 'Key actions · Local client edited' }).click()
  await page.getByRole('menuitem', { name: 'Enable', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Enable', exact: true }).click()
  await expect(editedRow).toContainText('Active')
  await editedRow.getByRole('button', { name: 'Key actions · Local client edited' }).click()
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(editedRow).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Create key', exact: true })).toBeFocused()
  await page.reload()
  await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(6)
  expect(writes).toEqual([])
  expect(await page.evaluate(() => Object.values({ ...sessionStorage, ...localStorage }).some((value) => String(value).includes('ovload-demo-')))).toBe(false)
})

test('clipboard failures are explicit and dirty editors require a discard decision', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new Error('denied')) } }))
  await page.goto('/user/api-keys')
  await page.getByRole('button', { name: 'Copy sample key · Workspace', exact: true }).click()
  await expect(page.getByText('Could not copy. Check clipboard permissions.')).toBeVisible()
  await page.getByRole('button', { name: 'Create key', exact: true }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Unsaved')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Create key', exact: true })).toBeFocused()
})

