test('subscription money and reset boundaries', () => {
  expect(parseCents('29.01')).toBe(2901)
  for (const v of ['-1', '1.001', '1e2', '', 'NaN', '99999999']) expect(parseCents(v)).toBeNull()
  for (const row of subscriptions) {
    const next = nextReset(row, 'daily')
    expect(next).toBeGreaterThan(previewNow)
    expect(next - previewNow).toBeLessThanOrEqual(day)
    expect(nextReset(row, 'monthly')).toBeGreaterThan(previewNow)
  }
  expect(statusOf(subscriptions[3])).toBe('expired')
  expect(statusOf(subscriptions[5])).toBe('revoked')
})
