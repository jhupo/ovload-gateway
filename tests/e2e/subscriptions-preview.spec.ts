test('subscription feedback clears before reopening an editor', async ({ browser }) => {
  for (const mobile of [false, true]) for (const theme of ['light', 'dark'] as const) {
    const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 }, colorScheme: theme, reducedMotion: 'reduce' })
    await page.addInitScript(() => { sessionStorage.setItem('ovload.admin-preview', 'active'); localStorage.setItem('i18nextLng', 'zh') })
    await page.goto('http://127.0.0.1:5191/orders/plans')
    const edit = page.getByRole('button', { name: '编辑 Standard', exact: true }).filter({ visible: true })
    await edit.click()
    const dialog = page.getByRole('dialog', { name: '编辑套餐', exact: true })
    await dialog.getByRole('textbox', { name: '每月额度', exact: true }).fill('999.99')
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(page.getByText('已更新本地预览', { exact: true })).toBeVisible()
    await page.waitForTimeout(300)
    await page.screenshot({ path: resolve(`output/subscriptions-qa/implementation/final-${mobile ? 'mobile' : 'desktop'}-${theme}-feedback.png`), animations: 'disabled' })
    await edit.click()
    await expect(page.getByText('已更新本地预览', { exact: true })).not.toBeVisible()
    await page.waitForTimeout(300)
    await page.screenshot({ path: resolve(`output/subscriptions-qa/implementation/final-${mobile ? 'mobile' : 'desktop'}-${theme}-editor.png`), animations: 'disabled' })
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    await page.evaluate(() => {history.pushState({}, '', '/subscriptions'); dispatchEvent(new PopStateEvent('popstate'))})
    const first = page.getByRole(mobile ? 'listitem' : 'row').filter({ hasText: 'lin.zhou' }).filter({ visible: true }).first()
    await expect(first).toContainText('$1,150.00')
    await expect(first).not.toContainText('$999.99')
    await page.close()
  }
})
