import {test,expect,type Page} from '../../web/node_modules/@playwright/test'
const storageKey='ovload.model-pricing.draft'
const save=(page:Page)=>page.getByRole('button',{name:'Save',exact:true}).filter({visible:true})
const dialog=(page:Page)=>page.getByRole('dialog')
const apply=(page:Page)=>dialog(page).getByRole('button',{name:'Apply to draft',exact:true})
async function fillRates(page:Page,input='1.2500') {
 for(const [label,value] of Object.entries({'Input':input,'Output':'10','Cache read':'0.0001','Cache write':'0'}))
  await dialog(page).getByLabel(label,{exact:true}).fill(value)
}
async function addPrice(page:Page,model='sample-model') {
 await page.getByRole('button',{name:'Add model price',exact:true}).click()
 await dialog(page).getByLabel('Exact model name',{exact:true}).fill(model)
 await fillRates(page)
 await apply(page).click()
 await expect(dialog(page)).toBeHidden()
}
