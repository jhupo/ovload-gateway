test('pricing save failures roll back gateway writes and retry preserves both drafts',async({page})=>{
 await page.getByRole('tab',{name:'Basic settings',exact:true}).click()
 await page.getByLabel('Connection timeout (s)',{exact:true}).fill('20')
 await save(page).click()
 const previous=await page.evaluate(()=>sessionStorage.getItem('ovload.gateway-settings.draft.v1'))
 await page.getByLabel('Connection timeout (s)',{exact:true}).fill('25')
 await page.getByRole('tab',{name:'Model pricing',exact:true}).click()
 await addPrice(page)
 await page.evaluate(key=>{
  const original=Storage.prototype.setItem
  ;(window as unknown as {restorePriceStorage:()=>void}).restorePriceStorage=()=>{Storage.prototype.setItem=original}
  Storage.prototype.setItem=function(k,v){if(k===key)throw new DOMException('Fixture failure','QuotaExceededError');return original.call(this,k,v)}
 },storageKey)
 await save(page).click()
 expect(await page.evaluate(()=>sessionStorage.getItem('ovload.gateway-settings.draft.v1'))).toBe(previous)
 expect(await page.evaluate(key=>sessionStorage.getItem(key),storageKey)).toBeNull()
 await expect(save(page)).toBeEnabled()
 await page.getByRole('tab',{name:'Basic settings',exact:true}).click()
 await expect(page.getByLabel('Connection timeout (s)',{exact:true})).toHaveValue('25')
 await page.evaluate(()=>(window as unknown as {restorePriceStorage:()=>void}).restorePriceStorage())
 await save(page).click()
 await expect(save(page)).toBeDisabled()
 expect(await page.evaluate(()=>JSON.parse(sessionStorage.getItem('ovload.gateway-settings.draft.v1')!).connectTimeout)).toBe('25')
 expect(await page.evaluate(key=>JSON.parse(sessionStorage.getItem(key)!).entries.length,storageKey)).toBe(1)
})
