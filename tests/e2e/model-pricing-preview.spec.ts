for (const width of [1440, 390]) test(`pricing keeps pagination visible while long pages scroll at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  const footer = page.getByRole('button', { name: 'Next page', exact: true })
  await expect(footer).toBeInViewport()
  const add = page.getByRole('button', { name: 'Add model price', exact: true })
  const view = page.getByRole('button', { name: 'View', exact: true })
  await expect(add.locator('..')).toContainText('View')
  if (width >= 1024) {
    const [addBox, viewBox] = await Promise.all([add.boundingBox(), view.boundingBox()])
    expect(Math.abs(addBox!.y - viewBox!.y)).toBeLessThan(1)
    expect(addBox!.x).toBeGreaterThan(viewBox!.x)
  } else {
    await expect(view).toBeHidden()
  }
  await page.evaluate(key => sessionStorage.setItem(key, JSON.stringify({ version: 1, entries: Array.from({ length: 60 }, (_, i) => ({ id: 'fixture-' + i, provider: 'openai', model: 'scroll-fixture-' + i, bands: { standard: { input: String(i), output: '0', cacheRead: '0', cacheWrite: '0' } } })) })), storageKey)
  await page.reload()
  await page.getByRole('tab', { name: 'Model pricing', exact: true }).click()
  await page.getByRole('combobox', { name: 'Rows per page', exact: true }).click()
  await page.getByRole('option', { name: '50', exact: true }).click()
  const table = page.getByRole('table', { name: 'Global base prices', exact: true })
  await expect(table.getByRole('row')).toHaveCount(51)
  const scroll = page.getByTestId('model-pricing-table-scroll')
  const bounds = await scroll.boundingBox()
  expect(bounds!.height).toBeGreaterThan(width > 1000 ? 300 : 100)
  const before = await footer.boundingBox()
  expect(before!.y + before!.height).toBeLessThan(900)
  await scroll.evaluate(el => { el.scrollTop = el.scrollHeight })
  await expect(footer).toBeInViewport()
  const after = await footer.boundingBox()
  expect(Math.abs(before!.y - after!.y)).toBeLessThan(1)
  const header = await table.locator('thead').boundingBox()
  expect(Math.abs(header!.y - bounds!.y)).toBeLessThan(3)
  await footer.click()
  await expect(table.getByRole('row')).toHaveCount(11)
  await expect(table.getByRole('cell', { name: 'scroll-fixture-50', exact: true })).toBeInViewport()
  expect(await scroll.evaluate(el => el.scrollTop)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
